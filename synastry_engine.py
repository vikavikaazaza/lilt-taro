def _display_strength(a: dict[str, Any], weight: float) -> str:
    orb=_orb(a)
    pair=_pair(a)
    asp=str(a.get('aspect',''))
    if pair == frozenset(('Луна','Луна')) and orb < 7:
        return 'заметная'
    if orb >= 7:
        return 'слабая'
    if asp in {'Соединение','Оппозиция','Квадрат','Тригон','Секстиль'} and orb <= 2:
        return 'высокая'
    if orb <= 4:
        return 'заметная'
    if orb <= 6:
        return 'умеренная'
    return 'слабая'


