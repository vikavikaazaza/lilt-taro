def score_topics(calc: dict[str, Any]) -> dict[str, float]:
    scores=defaultdict(float)
    for a in calc.get('aspects',[]):
        pair_rule=PAIR_RULES.get(_pair(a))
        if not pair_rule: continue
        topic=pair_rule[0]; w=aspect_weight(a)
        scores[topic]+=w
        if topic=='attraction': scores['passion']+=w*0.75
        if _pair(a)==frozenset(('Венера','Марс')): scores['passion']+=w*0.8
        if _pair(a)==frozenset(('Венера','Плутон')): scores['passion']+=w*0.65
        if _pair(a)==frozenset(('Марс','Плутон')): scores['passion']+=w*0.65
        if str(a.get('aspect','')) in {'Квадрат','Оппозиция'}: scores['conflicts']+=w*0.8
    for overlays_key, person_idx in [('overlays_1_in_2',2),('overlays_2_in_1',1)]:
        for x in calc.get(overlays_key,[]):
            h=int(x.get('house') or 0)
            rule=HOUSE_RULES.get(h)
            if rule:
                scores[rule[0]]+=2.5
                if h==8: scores['passion']+=3
    for a in calc.get('angle_aspects',[]):
        w=(ASPECT_BASE.get(str(a.get('aspect','')),3)+5)*orb_factor(float(a.get('orb',99)))
        point=str(a.get('point',''))
        if point in {'ASC','DSC'}: scores['attraction']+=w*0.8; scores['long_term']+=w*0.4
        if point in {'IC'}: scores['emotions']+=w*0.8
        if point in {'MC'}: scores['long_term']+=w*0.6
    return dict(scores)


def select_aspects(calc: dict[str, Any], limit: int | None = None) -> list[dict[str, Any]]:
    aspects=[]
    seen=set()
    for a in calc.get('aspects',[]):
        if _pair(a) not in PAIR_RULES: continue
        x=dict(a); x['rule_weight']=round(aspect_weight(a),2); x['aspect_tone']=ASPECT_TONE.get(str(a.get('aspect','')), '')
        key=(_pair(a), str(a.get('aspect','')))
        # Keep the most precise instance if duplicate pair/aspect occurs.
        if key in seen: continue
        seen.add(key); aspects.append(x)
    aspects.sort(key=lambda a:(-float(a.get('rule_weight',0)), _orb(a)))
    return aspects if limit is None else aspects[:limit]


