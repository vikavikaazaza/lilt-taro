def _detail(a: dict[str, Any], n1: str, n2: str, used_topics: set[str]|None=None, calc: dict[str, Any]|None=None) -> dict[str, Any]:
    p1,p2=str(a.get('person1_planet','')),str(a.get('person2_planet',''))
    asp=str(a.get('aspect','')); rule=PAIR_RULES.get(_pair(a))
    topic, core, label = rule if rule else ('general','важная тема отношений','отношения')
    meaning, manifestation, example, advice = _aspect_sentences(a,n1,n2)
    weight=round(aspect_weight(a),2)
    return {
      'title':f'{p1} — {asp} — {p2}',
      'topic':topic,'topic_label':label,'orb_text':str(a.get('orb_text','')),
      'weight':weight,'tone':ASPECT_TONE.get(asp,''),
      'what_it_gives':meaning,
      'how_it_appears':manifestation,
      'example':example,
      'advice':advice,
      'strength':'высокая' if weight>=12 else ('заметная' if weight>=7 else 'умеренная'),
      'difficulty':'напряжённая' if asp in {'Квадрат','Оппозиция'} else ('смешанная' if asp=='Соединение' else 'мягкая'),
      'person1_sign':a.get('person1_sign',''),'person2_sign':a.get('person2_sign',''),
    }


def _section_summary(details: list[dict[str, Any]], topic: str, fallback: str) -> str:
    ds=[d for d in details if d.get('topic')==topic]
    if not ds: return fallback
    # Только 2–3 разных факта, без копирования карточек аспектов.
    texts=[]
    for d in ds:
        t=str(d.get('what_it_gives','')).strip()
        if t and t not in texts: texts.append(t)
    return ' '.join(texts[:3])


