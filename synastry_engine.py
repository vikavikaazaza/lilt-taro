def _house_interpretation(h:int, planets:list[str], planet_owner:str, house_owner:str)->str:
    pg=', '.join(planets)
    owner=_case(planet_owner,'gen'); target=_case(house_owner,'gen')
    base=HOUSE_MEANINGS.get(h,'')
    if h==3 and 'Плутон' in planets:
        return f'Плутон {owner} в 3-м доме {target}: слова и мысли {_case(planet_owner,'gen')} могут глубоко влиять на {_case(house_owner,'acc')}. Разговоры способны давать ощущение близости, но при давлении — превращаться в допрос. {_case(house_owner,'dat')} важно не закрываться, а {_case(planet_owner,'dat')} — оставлять партнёру пространство для собственного мнения.'
    if h==8 and 'Луна' in planets:
        return f'Луна {owner} в 8-м доме {target}: эмоциональная связь быстро становится глубокой. {house_owner} может сильнее обычного чувствовать настроение {_case(planet_owner,'gen')}, ревновать или ждать подтверждения доверия. Здесь особенно важно говорить о чувствах и деньгах прямо.'
    if h==10 and any(p in planets for p in ('Венера','Юпитер')):
        return f'{pg} {owner} в 10-м доме {target}: {planet_owner} заметно влияет на цели и карьерные решения {_case(house_owner,'gen')}. Это может вдохновлять, поддерживать уверенность и открывать новые возможности, но важно не превращать поддержку в управление жизнью партнёра.'
    if h==9 and len(planets)>=3:
        return f'{pg} {owner} в 9-м доме {target}: большая часть связи {_case(planet_owner,'gen')} с {_case(house_owner,'ins')} проходит через планы, обучение, поездки и взгляды на будущее. Один может сильно расширять горизонт другого, но различия во взглядах придётся обсуждать, а не замалчивать.'
    if h==5 and 'Уран' in planets:
        return f'Уран {owner} в 5-м доме {target}: романтика может быть неожиданной и совсем не похожей на привычный сценарий. {house_owner} может особенно ярко чувствовать интерес {_case(planet_owner,'gen')}, но одновременно нуждаться в свободе и новизне.'
    if h==2 and planets:
        return f'{pg} {owner} во 2-м доме {target}: присутствие {_case(planet_owner,'gen')} затрагивает деньги, покупки и чувство опоры {_case(house_owner,'gen')}. Поэтому даже обычные финансовые решения могут восприниматься как вопрос доверия и вклада каждого.'
    if h==7 and 'Марс' in planets:
        return f'Марс {owner} в 7-м доме {target}: {planet_owner} сильно включает у {_case(house_owner,'gen')} тему партнёрства. Притяжение может быть быстрым, но так же быстро возникает спор о том, кто решает и как должны строиться отношения.'
    return f'{pg} {owner} в {h}-м доме {target}: {base}.'

def build_sections(calc: dict[str, Any]) -> list[dict[str, Any]]:
    n1,n2=str(calc.get('name1') or 'Человек 1'),str(calc.get('name2') or 'Человек 2')
    all_aspects=select_aspects(calc)
    details=[_detail(a,n1,n2,calc=calc) for a in all_aspects]
    featured=featured_aspects(calc,5)
    featured_details=[]
    for a in featured:
        if a.get('_kind')=='angle': featured_details.append(_angle_detail(a,n1,n2))
        else: featured_details.append(_detail(a,n1,n2,calc=calc))
    scores=score_topics(calc)
    labels={'attraction':'притяжение','emotions':'эмоции','communication':'общение','passion':'страсть','long_term':'долгосрочность','conflicts':'напряжение','freedom':'свобода'}
    visible=sorted(((k,v) for k,v in scores.items() if k in labels and v>0),key=lambda x:-x[1])
    lead='Главные темы этой связи — '+', '.join(labels[k] for k,_ in visible[:3])+'. ' if visible else 'В этой карте нет одной доминирующей темы. '
    hard=[a for a in all_aspects if _hard(a) and _orb(a)<7]
    soft=[a for a in all_aspects if _supportive(a) and _orb(a)<7]
    if hard and soft: lead+='У вас одновременно есть сильное притяжение и точки напряжения: именно сочетание этих двух вещей делает связь живой и требует ясных договорённостей.'
    elif hard: lead+='Основные сложности связаны с темпом, границами и разницей в способе реагировать.'
    else: lead+='Поддерживающих связей больше, поэтому многие важные вещи проще обсуждать и проживать вместе.'
    sections=[{'id':'summary','title':'🔮 Общая картина','text':lead,'items':[]},
              {'id':'top','title':'⭐ Что особенно заметно','text':'Здесь собраны самые сильные контакты между вашими картами — включая влияния на личность, образ партнёра и жизненный курс.','items':featured_details}]
    groups=[('attraction','❤️ Притяжение','Симпатия здесь связана не только с внешним интересом: важно, что именно заставляет вас тянуться друг к другу и хотеть продолжения контакта.'),('emotions','🌙 Эмоциональная связь','Главный вопрос здесь — чувствуете ли вы рядом друг с другом тепло, безопасность и понимание.'),('communication','🧠 Общение','Разговоры для этой пары — не фон. Через них вы сближаетесь, принимаете решения и иногда запускаете конфликт.'),('long_term','💍 Совместная жизнь и планы','Здесь важны деньги, обязанности, статус, работа и способность превращать планы в реальные действия.'),('conflicts','⚡ Где чаще всего задевает','Напряжение возникает там, где сталкиваются темп, свобода, контроль и ожидания.')]
    for topic,title,base in groups:
        ds=[d for d in details if d.get('topic')==topic]
        if not ds: continue
        highlights=[]
        for d in ds[:3]:
            s=str(d.get('what_it_gives','')).strip()
            if s and s not in highlights: highlights.append(s)
        sections.append({'id':topic,'title':title,'text':base+' '+' '.join(highlights),'items':[]})
    # Дома группируем по сферам, а внутри каждой сферы объединяем одинаковые дома.
    grouped=[]
    for bucket,planet_owner,house_owner in [('overlays_1_in_2',n1,n2),('overlays_2_in_1',n2,n1)]:
        by_house=defaultdict(list)
        for x in calc.get(bucket,[]):
            h=int(x.get('house') or 0)
            if h in HOUSE_MEANINGS: by_house[h].append(str(x.get('planet','')))
        for h, planets in by_house.items():
            grouped.append((h,planet_owner,house_owner,planets))
    by_category=defaultdict(list)
    for h,po,ho,planets in grouped:
        cat=next((k for k,v in HOUSE_GROUPS.items() if h in v),'Другие сферы')
        by_category[cat].append(_house_interpretation(h,planets,po,ho))
    if by_category:
        house_sections=[]
        for cat in ('Быт и семья','Романтика и дети','Доверие и деньги','Карьера и статус','Общение и поездки','Друзья и общие планы','Личное влияние'):
            vals=by_category.get(cat,[])
            if vals: house_sections.append({'id':'house_'+str(len(house_sections)),'title':cat,'text':' '.join(vals),'items':[]})
        sections.append({'id':'daily','title':'🏠 Как отношения проявляются в жизни','text':'Здесь собраны не просто номера домов, а ситуации, в которых влияние партнёра особенно заметно.','items':[],'subsections':house_sections})
    # Углы также получают отдельный смысловой блок, а не остаются техническим списком внизу.
    angle_details=[_angle_detail(a,n1,n2) for a in calc.get('angle_aspects',[])]
    angle_details.sort(key=lambda x:-float(x.get('weight',0)))
    if angle_details:
        sections.append({'id':'angles','title':'👤 Влияние на личность и образ партнёра','text':'Контакты с ASC, DSC, MC и IC показывают, как один человек влияет на самоощущение другого, его образ партнёра, карьерные цели и чувство дома.','items':angle_details})
    # Синтез связывает основные темы, а не повторяет список аспектов.
    synthesis=[]
    pairset={_pair(a) for a in all_aspects if _orb(a)<7}
    if frozenset(('Луна','Луна')) in pairset: synthesis.append('Эмоциональная база заметна: вы можете похожим образом переживать близость и потребность в заботе.')
    if frozenset(('Меркурий','Марс')) in pairset: synthesis.append('Интеллектуальная искра сильная, поэтому разговоры способны как быстро сближать вас, так и так же быстро превращаться в спор.')
    if frozenset(('Венера','Плутон')) in pairset or frozenset(('Марс','Плутон')) in pairset: synthesis.append('Притяжение связано с сильными чувствами, поэтому тема доверия и контроля может становиться особенно чувствительной.')
    if frozenset(('Марс','Уран')) in pairset or frozenset(('Уран','Марс')) in pairset: synthesis.append('Одновременно вам нужна свобода действий: давление и попытки всё контролировать способны резко усиливать напряжение.')
    if frozenset(('Сатурн','Венера')) in pairset or frozenset(('Солнце','Сатурн')) in pairset: synthesis.append('Есть и серьёзная сторона связи: отношения могут проверяться временем, обязательствами и готовностью подтверждать чувства поступками.')
    if angle_details and any(a.get('angle_point') in {'ASC','DSC'} and float(a.get('weight',0))>=4 for a in angle_details): synthesis.append('Контакты с углами карты усиливают личное впечатление: партнёр может ощущаться особенно значимым и заметно менять привычный образ себя.')
    if synthesis:
        sections.append({'id':'synthesis','title':'✨ Синтез','text':' '.join(synthesis[:7]),'items':[]})
    return sections

def build_report(calc: dict[str, Any]) -> dict[str, Any]:
    all_aspects=select_aspects(calc)
    n1,n2=str(calc.get('name1') or 'Человек 1'),str(calc.get('name2') or 'Человек 2')
    details=[_detail(a,n1,n2,calc=calc) for a in all_aspects]
    featured=featured_aspects(calc,5)
    featured_details=[_angle_detail(a,n1,n2) if a.get('_kind')=='angle' else _detail(a,n1,n2,calc=calc) for a in featured]
    scores=score_topics(calc)
    return {
      'names':{'person1':n1,'person2':n2},
      'aspect_count':len(calc.get('aspects',[])),
      'selected_count':len(details),
      'scores':{k:round(v,1) for k,v in scores.items()},
      'featured_aspects':featured_details,
      'selected_aspects':details,
      'sections':build_sections(calc),
      'method':{
          'house_system':'Плацидус',
          'rectification':False,
          'synastry_orbs':{'Солнце':8.0,'Луна':8.0,'Меркурий':6.0,'Венера':6.0,'Марс':6.0,'Юпитер':5.0,'Сатурн':5.0,'Уран':4.0,'Нептун':4.0,'Плутон':4.0},
          'angle_orb':5.0,
          'orb_factor':'до 1° — максимальная точность; 1–2° — очень сильная связь; 2–4° — заметная; 4–6° — рабочая; 7°+ — только в полном списке',
          'top_aspects':5,
          'all_aspects':'показываются отдельно',
      },
    }

def build_aspect_detail(a: dict[str, Any], name1: str, name2: str) -> dict[str, Any]:
    x=dict(a)
    x['rule_weight']=round(aspect_weight(x),2)
    return _detail(x,name1,name2)


def build_summary(calc: dict[str, Any]) -> dict[str, Any]:
    report=build_report(calc)
    return report['sections'][0] | {'scores':report['scores'],'selected_count':report['selected_count']}


def render_text_report(calc: dict[str, Any]) -> str:
    report=build_report(calc)
    blocks=[]
    for section in report['sections']:
        blocks.append(f"{section['title']}\n{section['text']}")
    return '\n\n'.join(blocks)
