def build_sections(calc: dict[str, Any]) -> list[dict[str, Any]]:
    n1,n2=str(calc.get('name1') or 'Человек 1'),str(calc.get('name2') or 'Человек 2')
    selected=select_aspects(calc)
    details=[_detail(a,n1,n2,calc=calc) for a in selected]
    scores=score_topics(calc)
    def top(topic, n=3): return [d for d in details if d['topic']==topic][:n]
    sections=[]
    labels={'attraction':'притяжение','emotions':'эмоциональная связь','communication':'общение','passion':'страсть','long_term':'долгосрочность','conflicts':'напряжение','freedom':'свобода'}
    themes=sorted(scores.items(),key=lambda x:-x[1])[:3]
    lead='Главные темы этой связи — '+', '.join(labels.get(k,k) for k,_ in themes)+'. ' if themes else 'В карте нет достаточно точных связей, чтобы выделить одну доминирующую тему. '
    hard=sum(1 for a in selected if str(a.get('aspect','')) in {'Квадрат','Оппозиция'})
    soft=sum(1 for a in selected if str(a.get('aspect','')) in {'Тригон','Секстиль'})
    if hard and soft: lead+='При этом рядом существуют и поддерживающие, и напряжённые связи, поэтому отношения могут одновременно притягивать и требовать усилий.'
    elif hard: lead+='Здесь особенно заметны ситуации, где разница в реакциях требует прямых договорённостей.'
    elif soft: lead+='Поддерживающих связей достаточно, чтобы многие вопросы решались через естественное взаимопонимание.'
    sections.append({'id':'summary','title':'❤️ Общая динамика','text':lead,'items':[]})

    # 02 Притяжение
    ds=top('attraction',4)
    sections.append({'id':'attraction','title':'❤️ Притяжение','text':' '.join(d['what_it_gives']+' '+d['how_it_appears'] for d in ds) if ds else 'Сильной отдельной темы притяжения среди отобранных связей не выделено.','items':ds})

    # 03 Эмоции
    ds=top('emotions',4)
    sections.append({'id':'emotions','title':'🌙 Эмоциональная совместимость','text':' '.join(d['what_it_gives']+' '+d['how_it_appears'] for d in ds) if ds else 'Эмоциональная связь лучше всего раскрывается через реальные поступки, заботу и то, как вы реагируете на изменения планов.','items':ds})

    # 04 Общение
    ds=top('communication',4)
    sections.append({'id':'communication','title':'🧠 Общение','text':' '.join(d['what_it_gives']+' '+d['how_it_appears'] for d in ds) if ds else 'Отдельной доминирующей связи общения не выделено. Важнее всего здесь проговаривать конкретные ожидания и договорённости.','items':ds})

    # 05 Страсть: отдельная тема, даже если исходные правила относятся к притяжению.
    passion=[]
    for d in details:
        pair=d['title']
        if any(x in pair for x in ('Венера —','Марс —')) and d['topic'] in {'attraction','conflicts'}:
            passion.append(d)
    sections.append({'id':'passion','title':'🔥 Страсть и интимная динамика','text':' '.join(d['how_it_appears']+' '+d['example'] for d in passion[:4]) if passion else 'Отдельного сильного показателя страстной динамики среди выбранных связей нет.','items':passion[:4]})

    # 06 Долгосрочность + бытовой контекст домов.
    ds=top('long_term',4)
    practical=[]
    for bucket in ('overlays_1_in_2','overlays_2_in_1'):
        for x in calc.get(bucket,[]):
            h=int(x.get('house') or 0); rule=HOUSE_RULES.get(h)
            if not rule: continue
            who=n2 if bucket=='overlays_1_in_2' else n1
            practical.append(f'{x.get("planet","")} {_case(who,"gen")} попадает в {h} дом партнёра: {rule[1]}.')
    long_text=' '.join(d['what_it_gives']+' '+d['how_it_appears'] for d in ds)
    if practical: long_text=(long_text+' ' if long_text else '')+' '.join(practical[:5])
    if not long_text: long_text='Здесь нет одной связи, которая сама по себе определяет будущее пары. Потенциал лучше оценивать по тому, как вы договариваетесь о времени, деньгах, быте, статусе и общих планах.'
    sections.append({'id':'long_term','title':'💍 Долгосрочный потенциал','text':long_text,'items':ds})

    # 07 Конфликты
    ds=top('conflicts',5)
    sections.append({'id':'conflicts','title':'⚡ Конфликты и сложные места','text':' '.join(d['how_it_appears']+' '+d['example'] for d in ds) if ds else 'Ярко выраженной отдельной конфликтной темы среди самых сильных связей не выделено. Если споры возникают, ищите причину в конкретной ситуации, а не в ярлыке о характере партнёра.','items':ds})

    # 08 Итог
    final_parts=[]
    if scores.get('attraction',0)>0: final_parts.append('вас может заметно тянуть друг к другу')
    if scores.get('emotions',0)>0: final_parts.append('эмоциональная реакция друг на друга выражена')
    if scores.get('conflicts',0)>0: final_parts.append('часть сильных связей требует работы с границами и реакциями')
    if scores.get('long_term',0)>0: final_parts.append('отношения затрагивают реальные планы и ответственность')
    final='В этой связи '+', '.join(final_parts)+'.' if final_parts else 'В этой связи нет одной доминирующей темы — многое зависит от реального поведения пары.'
    final+=' Сильные стороны лучше раскрываются там, где вы говорите о конкретных желаниях, деньгах, времени, границах и планах, а не рассчитываете, что другой человек сам догадается.'
    sections.append({'id':'final','title':'🔮 Итог','text':final,'items':[]})
    return sections


def build_report(calc: dict[str, Any]) -> dict[str, Any]:
    selected=select_aspects(calc)
    n1,n2=str(calc.get('name1') or 'Человек 1'),str(calc.get('name2') or 'Человек 2')
    details=[_detail(a,n1,n2,calc=calc) for a in selected]
    scores=score_topics(calc)
    return {
      'names':{'person1':n1,'person2':n2},
      'aspect_count':len(calc.get('aspects',[])),
      'selected_count':len(details),
      'scores':{k:round(v,1) for k,v in scores.items()},
      'selected_aspects':details,
      'sections':build_sections(calc),
      'method':{'orb_factor':'1°=1.0; 2°=0.9; 3°=0.75; 4°=0.5; 5–6°=0.25','max_aspects':24},
    }


def build_aspect_detail(a: dict[str, Any], name1: str, name2: str) -> dict[str, Any]:
    x=dict(a)
    x['rule_weight']=round(aspect_weight(x),2)
    return _detail(x,name1,name2)


def build_summary(calc: dict[str, Any]) -> dict[str, Any]:
    report=build_report(calc)
    return report['sections'][0] | {'scores':report['scores'],'selected_count':report['selected_count']}


def render_text_report(calc: dict[str, Any]) -> str:
    report=build_report(calc)
    blocks=[]
    for section in report['sections']:
        blocks.append(f"{section['title']}\n{section['text']}")
    return '\n\n'.join(blocks)
