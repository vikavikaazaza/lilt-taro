def _pair(a: dict[str, Any]) -> frozenset[str]:
    return frozenset((str(a.get('person1_planet','')), str(a.get('person2_planet',''))))


def _orb(a: dict[str, Any]) -> float:
    try: return float(a.get('orb', 99.0))
    except Exception: return 99.0


def orb_factor(orb: float) -> float:
    if orb <= 1: return 1.0
    if orb <= 2: return 0.9
    if orb <= 3: return 0.75
    if orb <= 4: return 0.5
    if orb <= 6: return 0.25
    return 0.1


def aspect_weight(a: dict[str, Any]) -> float:
    p1, p2 = str(a.get('person1_planet','')), str(a.get('person2_planet',''))
    return (ASPECT_BASE.get(str(a.get('aspect','')), 3) + (PLANET_IMPORTANCE.get(p1, 4) + PLANET_IMPORTANCE.get(p2, 4)) / 4) * orb_factor(_orb(a))


def classify_aspect(a: dict[str, Any]) -> str:
    asp = str(a.get('aspect',''))
    if asp in {'Тригон','Секстиль'}: return 'supportive'
    if asp in {'Квадрат','Оппозиция'}: return 'hard'
    return 'mixed'

def _hard(a: dict[str, Any]) -> bool:
    return str(a.get('aspect','')) in {'Квадрат','Оппозиция'}


def _supportive(a: dict[str, Any]) -> bool:
    return str(a.get('aspect','')) in {'Тригон','Секстиль','Соединение'}


