def _syn_narrative(calc: dict[str, Any]) -> list[tuple[str, str]]:
    n1, n2 = _name(calc, 1), _name(calc, 2)
    aspects = [a for a in sorted(list(calc.get('aspects', [])), key=_aspect_sort_key) if _syn_personal(a)]
    hard = [a for a in aspects if _hard(a)]
    supportive = [a for a in aspects if _supportive(a)]
    overlays = _overlay_map(calc)
    out: list[tuple[str, str]] = []
    used_pairs: set[frozenset[str]] = set()

    def take(items, limit):
        result=[]
        for a in items:
            pair=_pair_key(a)
            if pair in used_pairs:
                continue
            used_pairs.add(pair); result.append(a)
            if len(result)>=limit: break
        return result

    # 1 — самые сильные и понятные связи. Делаем раздел насыщенным, но каждая пара появляется здесь только один раз.
    main = take(sorted(aspects, key=_aspect_sort_key), 4)
    main_intro = (
        f'У {_name_case(n1,"gen")} и {_name_case(n2,"gen")} отношения могут одновременно давать близость, сильный интерес и поводы для споров. '
        'Особенно хорошо это видно не по красивым словам, а по тому, как вы проводите время вместе, принимаете решения и ведёте себя после разногласий.'
    )
    out.append(('1. Главная динамика отношений', _join([main_intro] + [_syn_aspect_story(a,n1,n2) for a in main]) ))

    # 2 — эмоции. Если эмоциональные пары уже разобраны, даём отдельную практическую часть без повторения.
    emo_pairs={frozenset(x) for x in [('Луна','Луна'),('Солнце','Луна'),('Луна','Венера'),('Луна','Марс'),('Луна','Сатурн'),('Луна','Уран'),('Луна','Нептун'),('Луна','Плутон')]}
    emo=take([a for a in aspects if _pair_key(a) in emo_pairs], 3)
    emo_text=['Эмоции здесь лучше не угадывать. Если одному нужна поддержка, пауза или больше внимания, это стоит сказать прямо.']
    emo_text += [_syn_aspect_story(a,n1,n2) for a in emo]
    if len(emo_text)==1:
        emo_text.append('В сложный день особенно важно учитывать усталость друг друга. Обычная фраза, сказанная не вовремя, может задеть сильнее, чем ожидалось.')
    out.append(('2. Эмоциональная совместимость', _join(emo_text)))

    # 3 — романтика и сексуальная часть.
    love_pairs={frozenset(x) for x in [('Венера','Марс'),('Солнце','Венера'),('Венера','Венера'),('Венера','Плутон'),('Венера','Нептун'),('Венера','Уран'),('Марс','Плутон'),('Марс','Уран')]}
    love=take([a for a in aspects if _pair_key(a) in love_pairs], 4)
    love_text=['В романтической стороне пары особенно важны внимание, добровольность и реальные поступки. Сильное притяжение само по себе не решает вопросы доверия и границ.']
    love_text += [_syn_aspect_story(a,n1,n2) for a in love]
    if hard and not love:
        love_text.append('Если возникает ревность или напряжение, близость лучше не использовать как способ получить подтверждение любви или заставить партнёра уступить.')
    out.append(('3. Любовь, притяжение и интимная совместимость', _join(love_text)))

    # 4 — только ещё не использованные сложные связи.
    conflict_pairs={frozenset(x) for x in [('Марс','Марс'),('Марс','Сатурн'),('Марс','Плутон'),('Марс','Уран'),('Меркурий','Марс'),('Меркурий','Сатурн'),('Меркурий','Нептун'),('Меркурий','Плутон'),('Луна','Марс'),('Луна','Плутон'),('Солнце','Плутон'),('Сатурн','Уран')]}
    conf=take([a for a in hard if _pair_key(a) in conflict_pairs], 4)
    conflict_text=[_syn_aspect_story(a,n1,n2) for a in conf]
    conflict_text += [
        'Самая частая ошибка в таких ситуациях — спорить только о фактах. За обычной претензией часто стоят обида, страх, ревность или ощущение, что тебя не слышат.',
        'Если разговор начался в переписке и стал резко жёстким, лучше перейти к обычному разговору. Интонацию в сообщениях легко понять неправильно.'
    ]
    out.append(('4. Конфликты, ревность и болезненные точки', _join(conflict_text)))

    # 5 — дома, без копирования аспектов.
    practical=[]; shown_houses=set()
    for idx,target in ((1,n1),(2,n2)):
        present=[h for h in range(2,13) if overlays.get((idx,h))]
        for h in sorted(present):
            key=(idx,h)
            if key in shown_houses: continue
            shown_houses.add(key); practical.append(_syn_house_story(target,h,overlays.get((idx,h),[])))
            if len(practical)>=6: break
        if len(practical)>=6: break
    if not practical:
        practical=['В совместной жизни больше всего будут проверяться деньги, время, обязанности и личное пространство.']
    out.append(('5. Совместная жизнь, деньги и личное пространство', _join(practical)))

    # 6 — оставшиеся уникальные пары. Здесь даём конкретику, но не повторяем уже рассказанное.
    extra=take(aspects,6)
    extra_text=[_syn_aspect_story(a,n1,n2) for a in extra]
    if extra_text:
        out.append(('6. Что особенно важно в ваших отношениях', _join(extra_text)))
    else:
        out.append(('6. Что особенно важно в ваших отношениях', 'Даже без дополнительных связок многое будет зависеть от простых вещей: умеете ли вы говорить о своих желаниях, соблюдать договорённости и оставлять друг другу личное пространство.'))

    # 7 — реальные сценарии, только из домов/углов. Не повторяет раздел 5 дословно.
    scenarios=[]
    for a in calc.get('angle_aspects',[]):
        point=str(a.get('point',''))
        if point=='DSC': scenarios.append('Партнёр может очень сильно влиять на представление о том, какими должны быть близкие отношения. Поэтому вопрос «какой человек мне нужен рядом» может меняться под влиянием этой связи.')
        elif point=='ASC': scenarios.append('Реакция друг на друга может быть быстрой. Внешность, голос, настроение и манера поведения способны сразу вызывать сильный отклик.')
        elif point=='MC': scenarios.append('Отношения могут влиять на карьерные планы и большие решения. Партнёр способен становиться первым человеком, с которым хочется обсудить важный шаг.')
        elif point=='IC': scenarios.append('Рядом друг с другом сильнее включается тема дома и внутреннего чувства безопасности. Поэтому вопросы жилья и семьи могут иметь особый эмоциональный вес.')
    all_houses=sorted({h for idx in (1,2) for h in range(2,13) if overlays.get((idx,h))})
    for h in all_houses:
        if len(scenarios)>=5: break
        s=_syn_scenario_for_house(h)
        if s not in scenarios: scenarios.append(s)
    if not scenarios:
        scenarios=[
            'Большая часть характера пары будет видна в обычных ситуациях: встречах, переписке, деньгах, планах и распределении времени.',
            'Самая показательная проверка — момент, когда один устал или не согласен. Именно тогда видно, умеете ли вы оставаться на одной стороне, даже споря друг с другом.'
        ]
    out.append(('7. Что реально может происходить между вами', _join(scenarios[:5])))

    # 8 — длинная дистанция. Не копируем разделы 1–7.
    long=[]
    pairset={_pair_key(a) for a in aspects}
    if pairset & {frozenset(x) for x in [('Венера','Сатурн'),('Солнце','Сатурн'),('Марс','Сатурн'),('Юпитер','Сатурн')]}:
        long.append('Для долгих отношений особенно важны надёжность и выполненные обещания. Чем понятнее обязанности и планы, тем спокойнее становится связь.')
    if pairset & {frozenset(x) for x in [('Сатурн','Уран'),('Венера','Уран'),('Солнце','Уран')]}:
        long.append('Потребность в свободе может периодически сталкиваться с желанием стабильности. Правила пары лучше пересматривать, когда меняется работа, место жизни или привычный ритм.')
    if pairset & {frozenset(x) for x in [('Венера','Плутон'),('Луна','Плутон'),('Марс','Плутон')]}:
        long.append('Если отношения становятся серьёзными, особенно важны доверие и способность говорить о страхе потери без проверок, угроз и давления.')
    if overlays.get((1,4)) or overlays.get((2,4)):
        long.append('Совместный дом со временем становится отдельной частью отношений. Быт и семейные правила лучше обсуждать заранее, а не надеяться, что всё само собой устроится.')
    if not long:
        long.append('На длинной дистанции отношения будут проверяться обычной жизнью: деньгами, обязанностями, личным пространством, планами и тем, как вы возвращаетесь к разговору после ссоры.')
    out.append(('8. Что происходит с отношениями на длинной дистанции', _join(long)))

    # 9 — короткий, но содержательный вывод без повторения конкретных фраз.
    summary=[
        f'У {_name_case(n1,"gen")} и {_name_case(n2,"gen")} отношения не сводятся к одной теме. В них одновременно важны близость, личная свобода, разговоры и реальные бытовые решения.'
    ]
    if hard: summary.append('Самая сложная часть — не отсутствие чувств, а моменты, когда обида превращается в давление, молчание или борьбу за последнее слово.')
    if supportive: summary.append('Хорошая опора — способность сохранять контакт и делать что-то вместе даже тогда, когда ваши желания не совпадают.')
    summary.append('Поэтому для этой пары особенно важны простые вещи: говорить прямо, выполнять обещания и не заставлять партнёра угадывать, что происходит внутри.')
    out.append(('9. Итог', _join(summary)))

    # Удаляем только точные дубли, не вырезая разные мысли.
    seen=set(); cleaned=[]
    for title,body in out:
        kept=[]
        for sent in re.split(r'(?<=[.!?])\s+',body.strip()):
            key=re.sub(r'\s+',' ',sent).strip().lower()
            if key and key not in seen:
                seen.add(key); kept.append(sent.strip())
        cleaned.append((title,' '.join(kept)))
    return cleaned


def build_synastry_interpretation(calc: dict[str, Any]) -> str:
    return '\n\n'.join(title + '\n' + body for title, body in _syn_narrative(calc))


def _pair_technical(a: dict[str, Any], n1: str, n2: str) -> str:
    return (
        f"{n1}: {a.get('person1_planet','')} ({a.get('person1_sign','')} {a.get('person1_position','')}) "
        f"{a.get('aspect','')} {n2}: {a.get('person2_planet','')} "
        f"({a.get('person2_sign','')} {a.get('person2_position','')}); "
        f"орб {a.get('orb_text','')}; {a.get('relationship_weight','')}"
    )


def synastry_pdf_sections(calc: dict[str, Any]) -> list[tuple[str, list[str]]]:
    n1, n2 = _name(calc, 1), _name(calc, 2)
    aspects = sorted(list(calc.get('aspects', [])), key=_aspect_sort_key)
    sections = [(title, [body]) for title, body in _syn_narrative(calc)]
    sections.append(
        ('Техническая таблица аспектов',
         [_pair_technical(a, n1, n2) for a in aspects] or ['Значимых аспектов в заданных орбисах не найдено.'])
    )
    return sections


