        o.append('Напряжение тоже заметно, но оно сосредоточено вокруг конкретных механизмов: реакций, границ, внимания, темпа действий, слов и ожиданий. Это означает, что многие трудности потенциально решаемы навыком взаимодействия, а не требуют полного совпадения характеров.')
