def _transit_action(a: dict[str, Any]) -> str:
    topics = _transit_topics(a)
    if 'documents' in topics:
        return 'проверить документ и зафиксировать договорённость письменно'
    if 'money' in topics:
        return 'проверить сумму и сразу определить, кто, сколько и к какому сроку платит'
