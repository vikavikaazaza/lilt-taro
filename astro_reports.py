    """Совместимость эмоциональных показателей. Сохраняет старый публичный API."""
    return [
        a for a in aspects
        if _is_pair(a, 'Луна', 'Венера')
        or _is_pair(a, 'Луна', 'Луна')
        or _is_pair(a, 'Луна', 'Марс')
        or _is_pair(a, 'Солнце', 'Луна')
    ]
