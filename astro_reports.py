def _syn_unique_aspects(items: list[dict[str, Any]], used: set[frozenset[str]]) -> list[dict[str, Any]]:
    out = []
    for a in items:
        pair = _pair_key(a)
        if pair in used:
            continue
        out.append(a)
        used.add(pair)
    return out


