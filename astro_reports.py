def _timing_phrase(a: dict[str, Any]) -> str:
    tp = str(a.get('transit_planet', ''))
    state = str(a.get('state', ''))
    if tp == 'Луна': horizon = 'часы и ближайшие сутки'
    elif tp in {'Солнце', 'Меркурий', 'Венера', 'Марс'}: horizon = 'ближайшие дни и недели'
    elif tp in {'Юпитер', 'Сатурн'}: horizon = 'недели и месяцы'
    else: horizon = 'месяцы и более длинный период'
    if state == 'точный': return f'На выбранную дату эта тема находится в непосредственной точке проявления; особенно заметным может быть горизонт {horizon}.'
    if state == 'сходящийся': return f'Тема ещё усиливается; ориентир для наблюдения - {horizon}.'
    return f'Тема постепенно отходит от максимума; основные последствия могут разворачиваться в горизонте {horizon}.'


def _transit_narrative(calc: dict[str, Any], aspects: list[dict[str, Any]]) -> list[tuple[str, str]]:
    top = aspects[:12]
    hard = [a for a in aspects if _hard(a)]
    support = [a for a in aspects if _supportive(a)]
    long = [a for a in aspects if str(a.get('transit_planet')) in {'Юпитер', 'Сатурн', 'Уран', 'Нептун', 'Плутон'}]
    work = [a for a in aspects if str(a.get('transit_planet')) in {'Меркурий', 'Венера', 'Марс', 'Юпитер', 'Сатурн', 'Уран'}]
    rel = [a for a in aspects if str(a.get('transit_planet')) in {'Венера', 'Марс', 'Юпитер', 'Уран', 'Нептун', 'Плутон'} or str(a.get('natal_planet')) in {'Венера', 'Марс', 'Солнце', 'Луна'}]
    out: list[tuple[str, str]] = []

    def unique(items: list[dict[str, Any]], key_func) -> list[dict[str, Any]]:
        seen=set(); result=[]
        for item in items:
            key=key_func(item)
            if key in seen:
                continue
            seen.add(key); result.append(item)
        return result

    def event_phrase(a: dict[str, Any], hard_mode: bool | None = None) -> str:
        tp=str(a.get('transit_planet','')); np=str(a.get('natal_planet',''))
        hard_flag=_hard(a) if hard_mode is None else hard_mode
        house=int(a['house']) if a.get('house') else None
        return _transit_event_phrase(tp,np,hard_flag,house)

    main=[]
    if top:
        houses=Counter(int(a['house']) for a in top if a.get('house'))
        if houses:
            h=houses.most_common(1)[0][0]
            main.append(f'На выбранную дату сильнее всего активирована сфера {HOUSE_THEME.get(h, "этой части жизни")}. Именно здесь уже начавшиеся процессы могут получить движение, новый разговор, решение или необходимость поменять привычный порядок действий.')
        themes=[]
        for a in top:
            t=PLANET_ROLE.get(str(a.get('natal_planet','')))
            if t and t not in themes: themes.append(t)
        if themes:
            main.append('На этом фоне одновременно затрагиваются ' + ', '.join(themes[:4]) + '. Поэтому день может ощущаться насыщенным: изменения в одной области способны сразу отражаться на другой, например решение по работе меняет финансовый план или разговор с человеком заставляет пересмотреть дальнейшие шаги.')
