def _syn_theme_counts(aspects: list[dict[str, Any]]) -> Counter:
    c = Counter()
    for a in aspects:
        pair = _pair_key(a)
        if pair & {'Солнце','Луна'}:
            c['эмоциональная связь'] += 1
        if pair & {'Венера','Марс'}:
            c['притяжение'] += 1
        if pair & {'Меркурий','Нептун'}:
            c['понимание'] += 1
        if pair & {'Марс','Сатурн'}:
            c['темп и обязанности'] += 1
        if pair & {'Плутон','Венера','Марс'}:
            c['доверие и границы'] += 1
        if pair & {'Юпитер','Сатурн'}:
            c['совместные планы'] += 1
        if pair & {'Уран'}:
            c['свобода и перемены'] += 1
    return c


def _syn_scenario_list(aspects: list[dict[str, Any]], n1: str, n2: str) -> list[str]:
    n1n, n2n = _name_case(n1, 'nom'), _name_case(n2, 'nom')
    out: list[str] = []
    pairs = {_pair_key(a) for a in aspects}

    if _pair('Венера','Марс') in pairs:
        out.append(f'Сближение. {n1n} и {n2n} могут довольно быстро переходить от симпатии к встречам и физической близости. Особенно хорошо работает совместная активность: поездка, прогулка, дело, после которого хочется остаться вдвоём.')
    if _pair('Солнце','Марс') in pairs or _pair('Марс','Сатурн') in pairs:
        out.append('Спор из-за темпа. Один уже хочет решить вопрос, а второй просит не торопиться. Поводом может стать покупка, ремонт, поездка, работа или решение о переезде; спор постепенно смещается с самой задачи на то, кто задаёт правила.')
    if _pair('Меркурий','Нептун') in pairs:
        out.append('Разговор, который сначала кажется простым. Одна фраза может быть понята по-разному, особенно если речь идёт о деньгах, статусе отношений или будущем. Лучше сразу уточнить, что именно каждый имел в виду.')
    if _pair('Венера','Плутон') in pairs or _pair('Марс','Плутон') in pairs:
        out.append('Проверка границ. Обычная ситуация — позднее сообщение, внимание к другому человеку, желание побыть одному — может неожиданно вывести разговор на ревность, доверие и контроль.')
    if _pair('Уран','Венера') in pairs or _pair('Уран','Меркурий') in pairs:
        out.append('Неожиданный поворот. Встреча может внезапно поменяться, появится новая идея или один из партнёров предложит другой формат общения. Для этой связи полезно оставлять немного свободы вместо попытки заранее расписать всё до мелочей.')
    if _pair('Юпитер','Сатурн') in pairs:
        out.append('Большой совместный план. Идея о переезде, обучении, накоплениях, работе или общем проекте получает шанс стать реальной, когда появляются конкретные сроки, сумма и распределение ответственности.')

    return out[:6]


def _syn_narrative(calc: dict[str, Any]) -> list[tuple[str, str]]:
    n1, n2 = _name(calc, 1), _name(calc, 2)
    all_aspects = sorted(list(calc.get('aspects', [])), key=_aspect_sort_key)
    aspects = [a for a in all_aspects if _syn_personal(a)]
    hard = [a for a in aspects if _hard(a)]
    supportive = [a for a in aspects if _supportive(a)]
    angles = _angle_points(calc)
    overlays = _overlay_map(calc)
    out: list[tuple[str, str]] = []

    def has_pair(left: str, right: str, hard_only: bool = False) -> bool:
        return any(_is_pair(a, left, right) and (not hard_only or _hard(a)) for a in aspects)

    # 1. Не перечисляем планеты: сразу собираем несколько ведущих линий пары.
    themes = _syn_theme_counts(aspects)
    lead_text = []
    if themes['притяжение']:
        lead_text.append('сильное притяжение и желание быть рядом')
    if themes['доверие и границы']:
        lead_text.append('чувствительность к границам, ревности и доверию')
    if themes['понимание']:
        lead_text.append('важность разговоров и точного понимания друг друга')
    if themes['темп и обязанности']:
        lead_text.append('разный темп действий и отношение к обязанностям')
    if themes['свобода и перемены']:
        lead_text.append('потребность в свободе и изменении привычного формата')
    if themes['совместные планы']:
        lead_text.append('способность превращать общие идеи в конкретные планы')
    if themes['эмоциональная связь']:
        lead_text.append('сильная эмоциональная реакция друг на друга')
    if lead_text:
        if len(lead_text) > 4:
            lead_text = lead_text[:4]
        intro = f'У {_name_case(n1, "gen")} и {_name_case(n2, "gen")} отношения держатся сразу на нескольких линиях: ' + '; '.join(lead_text) + '.'
    else:
        intro = f'У {_name_case(n1, "gen")} и {_name_case(n2, "gen")} связь не сводится к одной теме: многое раскрывается через повседневные решения и то, как люди договариваются между собой.'

    key = []
    for a in aspects:
        t = _syn_aspect_detail(a, n1, n2)
        if t:
            key.append(t)
        if len(key) == 3:
            break
    p = [intro]
    if hard:
        p.append('Самые чувствительные места связаны не с отсутствием чувств, а с тем, как каждый отстаивает своё: кто решает, кто уступает, сколько нужно свободы и как обсуждать деньги, планы и обязанности.')
    if key:
        p.append('Например, ' + ' '.join(key))
    out.append(('1. Главная динамика отношений', _join(p)))

    # 2. Эмоции: кто как реагирует и что помогает не промахнуться мимо потребности другого.
    e = []
    if has_pair('Луна','Венера'):
        e.append(f'{_name_case(n1, "gen")} легче чувствовать близость через заботу и внимание: важны не только слова, но и то, что человек делает в обычный день.')
    if has_pair('Луна','Марс'):
        e.append('Эмоции быстро переходят в действие. Если один хочет сначала выговориться, а второй сразу начинает искать решение, каждый может решить, что его не услышали.')
    if has_pair('Солнце','Луна'):
        e.append(f'Решения {_name_case(n1, "gen")} способны напрямую затрагивать чувство безопасности {_name_case(n2, "gen")}. Поэтому при разговорах о будущем важно обсуждать не только цель, но и то, насколько комфортен сам путь к ней.')
    if has_pair('Луна','Луна'):
        e.append('У людей может быть разный способ переживать стресс: одному нужен разговор и контакт, другому — пауза. Если это не проговаривать, пауза легко принимается за холодность.')
    if not e:
        e.append('Эмоциональная близость здесь сильнее всего поддерживается простой вещью: говорить о своих потребностях до того, как накопится раздражение.')
    out.append(('2. Эмоциональная близость', _join(e)))

    # 3. Любовь и интимность — только про эту сферу.
    atext = []
    if has_pair('Венера','Марс'):
        atext.append('Физическое притяжение заметное: симпатия легче переходит в желание встретиться, прикоснуться и побыть вдвоём. Совместная активность дополнительно усиливает интерес.')
    if has_pair('Солнце','Венера'):
        atext.append('Важна взаимная симпатия. Комплименты, внимание, ощущение собственной привлекательности рядом с партнёром и простые знаки интереса заметно поддерживают отношения.')
    if has_pair('Венера','Плутон'):
        atext.append('Чувства могут переживаться очень интенсивно. Поэтому дистанция или внимание партнёра к кому-то ещё способны задевать сильнее, чем ожидалось; здесь особенно важны доверие и отсутствие игр на ревности.')
    if has_pair('Венера','Уран'):
        atext.append('Отношениям нужна свежесть. Необычное свидание, спонтанная поездка или возможность иногда менять привычный сценарий помогает сохранять интерес.')
    if has_pair('Венера','Сатурн'):
        atext.append('Симпатия проверяется поступками: насколько человек держит слово, появляется тогда, когда обещал, и готов вкладываться не только в романтические моменты.')
    if not atext:
        atext.append('Романтическая сторона отношений раскрывается прежде всего через реальные встречи, внимание и то, насколько оба находят время друг для друга.')
    out.append(('3. Любовь, притяжение и интимность', _join(atext)))

    # 4. Конфликты — только повторяющиеся механизмы.
    c = []
    if has_pair('Марс','Сатурн', True):
        c.append('Главный конфликтный механизм — разный темп. Один хочет решить вопрос сразу, второй останавливает, проверяет и просит подождать. В совместной жизни это особенно заметно на крупных тратах, ремонте, переезде и работе со сроками.')
    if has_pair('Солнце','Марс', True):
        c.append('В споре быстро появляется вопрос лидерства. Даже если предмет разговора небольшой, обсуждение может незаметно превратиться в борьбу за право решать первым.')
    if has_pair('Меркурий','Нептун', True):
        c.append('Вторая точка риска — недосказанность. Один считает, что мысль очевидна, другой понимает её иначе. Особенно опасны намёки в разговорах о деньгах, верности, статусе и будущем.')
    if has_pair('Венера','Плутон', True) or has_pair('Марс','Плутон', True):
        c.append('Тема контроля может включаться через ревность, проверки, попытку узнать всё до мелочей или требование постоянного подтверждения чувств. Чем сильнее давление, тем быстрее возникает сопротивление.')
    if not c:
        c.append('Явной повторяющейся схемы ссор здесь нет. Конфликты скорее зависят от конкретных обстоятельств, чем запускаются одним и тем же механизмом.')
    out.append(('4. Конфликты и точки трения', _join(c)))

    # 5. Реальная жизнь: дома, деньги, работа, планы.
    practical = []
    for target_idx, target_name in ((1, n1), (2, n2)):
        gen = _name_case(target_name, 'gen')
        present = [(h, overlays.get((target_idx, h), [])) for h in range(2, 13) if overlays.get((target_idx, h))]
        for h, planets in sorted(present, key=lambda x: (-len(x[1]), x[0]))[:2]:
            if h == 2: practical.append(f'У {_name_case(target_name, "gen")} отношения затрагивают деньги и личные ресурсы: расходы, крупные покупки и вклад каждого лучше обсуждать заранее.')
            elif h == 3: practical.append(f'У {_name_case(target_name, "gen")} связь сильно завязана на переписку, поездки и ежедневные договорённости. Здесь важно не оставлять без ответа вопросы, которые для второго уже стали срочными.')
            elif h == 4: practical.append(f'Для {_name_case(target_name, "gen")} особенно важны дом и личное пространство. Совместный быт лучше строить на заранее понятных правилах, а не на ожидании, что другой сам догадается.')
            elif h == 5: practical.append(f'Для {_name_case(target_name, "gen")} важно, чтобы отношения не превращались только в список дел. Свидания, поездки и совместные удовольствия помогают сохранять романтическую часть связи.')
            elif h == 6: practical.append(f'У {_name_case(target_name, "gen")} отношения проверяются ежедневной нагрузкой: кто готовит, кто организует, кто решает бытовые вопросы и насколько справедливо распределено время.')
            elif h == 7: practical.append(f'Для {_name_case(target_name, "gen")} партнёрство занимает заметное место. Поэтому естественными становятся разговоры о статусе, будущем и правилах отношений.')
            elif h == 8: practical.append(f'Для {_name_case(target_name, "gen")} особенно чувствительны общие деньги, доверие и интимность. Здесь лучше заранее договориться о границах и финансовых правилах.')
            elif h == 9: practical.append(f'Для {_name_case(target_name, "gen")} отношения связаны с поездками, обучением и расширением горизонта. Совместный интерес к новому способен укреплять связь.')
            elif h == 10: practical.append(f'Для {_name_case(target_name, "gen")} партнёр может заметно влиять на карьерные решения и жизненное направление. Поддержка здесь полезнее попытки управлять выбором другого.')
            elif h == 11: practical.append(f'Для {_name_case(target_name, "gen")} важны общие планы, друзья и проекты. Пара получает дополнительную опору, когда у неё есть совместная цель вне самих отношений.')
            elif h == 12: practical.append(f'У {_name_case(target_name, "gen")} часть переживаний может оставаться внутри. Поэтому лучше говорить о неприятном коротко и вовремя, чем ждать, пока накопится обида.')
    if not practical:
        practical.append('В реальной жизни совместимость будет проверяться простыми вещами: деньги, время, обязанности, личное пространство и способность договариваться о планах.')
    out.append(('5. Совместная жизнь и реальные сценарии', _join(practical)))

    # 6. Только сцены, без повторного перечня аспектов.
    scenarios = _syn_scenario_list(aspects, n1, n2)
    if not scenarios:
        scenarios = ['Здесь нет одной повторяющейся сцены, которая описывала бы всю связь. Конкретные события будут сильнее зависеть от обстоятельств и решений пары.']
    out.append(('6. Что конкретно может происходить между партнёрами', _join(scenarios)))

    # 7. Будущее — из реально поддержанных факторов.
    longterm = []
    if has_pair('Венера','Сатурн'):
        longterm.append('Связь может становиться серьёзнее через поступки: держать слово, выдерживать бытовые сложности и постепенно договариваться о будущем.')
    if has_pair('Юпитер','Сатурн'):
        longterm.append('Есть хороший механизм для больших общих задач: идея получает форму, когда появляются сроки, бюджет и распределение ответственности.')
    if angles['DSC'] or overlays.get((1,7)) or overlays.get((2,7)):
        longterm.append('Партнёрская тема выражена заметно, поэтому вопрос «что именно мы строим» со временем становится важнее самой романтики.')
    if angles['IC'] or overlays.get((1,4)) or overlays.get((2,4)):
        longterm.append('Дом и место, где пара живёт, могут сильно влиять на отношения. Решения о переезде, быте и семейных правилах лучше принимать вместе.')
    if not longterm:
        longterm.append('Долгосрочный потенциал лучше всего проверяется реальной жизнью: выдерживают ли отношения разговоры о деньгах, границах, быте, будущем и разнице в темпе.')
    out.append(('7. Потенциал на будущее', _join(longterm)))

    # 8. Итог без морализаторства и повторов.
    final = [f'Связь {_name_case(n1, "gen")} и {_name_case(n2, "gen")} заметна именно в реальной жизни: чувства здесь быстро упираются в решения, границы, время, деньги и планы.']
    if hard:
        final.append('Главное место для внимания — не сами разногласия, а то, как пара проходит их: без молчаливых проверок, борьбы за власть и попыток угадать мысли друг друга.')
    if supportive:
        final.append('При этом у пары есть ресурсы для восстановления контакта: разговор, совместные дела, чувство юмора, общие планы или способность снова находить близость после напряжения.')
    final.append('Поэтому отношения лучше всего раскрываются там, где оба могут прямо сказать, чего хотят, на что готовы, где проходит их граница и каким они видят общий формат.')
    out.append(('8. Итог', _join(final)))
    return out


def build_synastry_interpretation(calc: dict[str, Any]) -> str:
    return '\n\n'.join(title + '\n' + body for title, body in _syn_narrative(calc))

