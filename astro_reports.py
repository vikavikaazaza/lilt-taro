def _syn_interesting_facts(calc: dict[str, Any]) -> list[str]:
    """Отдельный блок живых и конкретных фактов о паре.

    Все наблюдения строятся только из реально рассчитанных аспектов,
    углов, домовых попаданий и орбисов. Это не рейтинг совместимости.
    """
    n1, n2 = _name(calc, 1), _name(calc, 2)
    aspects = [a for a in calc.get('aspects', []) if _syn_personal(a)]
    angles = calc.get('angle_aspects', []) or []
    overlays = _overlay_map(calc)
    facts: list[str] = []

    def has_pair(left: str, right: str, hard_only: bool = False) -> bool:
        return any(_is_pair(a, left, right) and (not hard_only or _hard(a)) for a in aspects)

    def add(text: str) -> None:
        if text and text not in facts:
            facts.append(text)

    # Самые точные аспекты — фактический «скелет» интересного блока.
    tight = sorted(aspects, key=_orb)[:4]
    if tight:
        labels = [_syn_label(a, n1, n2) + f" (орб {_orb(a):.1f}°)" for a in tight]
        add('Самые точные связи пары: ' + '; '.join(labels) + '. В астрологической интерпретации именно точные контакты получают больший вес: чем меньше орб, тем точнее аспект и тем разумнее учитывать его при разборе повторяющихся тем пары — притяжения, общения, конфликтов и совместных решений. Это не означает, что аспект обязательно проявляется сильнее любого другого: значение также зависит от планет, домов и угловых точек.')

    # Эмоциональная реакция.
    moon = [a for a in aspects if 'Луна' in (a.get('person1_planet'), a.get('person2_planet'))]
    if moon:
        a = min(moon, key=_orb)
        add(f'Эмоциональный центр пары связан с Луной: {_syn_label(a, n1, n2)}. Поэтому реакция на другого может включаться раньше рассуждений: сначала появляется тепло, тревога, раздражение или желание приблизиться, а уже потом человек объясняет себе, почему его так задела конкретная ситуация.')

    # Романтическое и физическое притяжение.
    attraction = [a for a in aspects if _is_pair(a, 'Венера', 'Марс') or _is_pair(a, 'Венера', 'Плутон') or _is_pair(a, 'Марс', 'Плутон')]
    if attraction:
        a = min(attraction, key=_orb)
        add(f'Сильная сторона притяжения: {_syn_label(a, n1, n2)}. Здесь интерес может ощущаться не только как симпатия, но и как физическая реакция на присутствие другого. Поэтому взгляд, прикосновение, расстояние, отказ во встрече или внимание к третьему человеку способны иметь для этой пары гораздо больший эмоциональный вес, чем кажется со стороны.')

    # Борьба за инициативу.
    action = [a for a in aspects if _is_pair(a, 'Солнце', 'Марс') or _is_pair(a, 'Марс', 'Сатурн') or _is_pair(a, 'Марс', 'Плутон')]
    if action:
        a = min(action, key=_orb)
        add(f'В отношениях много энергии действия: {_syn_label(a, n1, n2)}. Поэтому обычные решения могут превращаться в вопрос лидерства: кто первым предлагает, кто меняет план, кто принимает окончательное решение и кто должен уступить. В хорошем сценарии это даёт паре скорость; в напряжённом — соревнование за право делать по-своему.')

    # Общение.
    mental = [a for a in aspects if _is_pair(a, 'Меркурий', 'Венера') or _is_pair(a, 'Меркурий', 'Солнце') or _is_pair(a, 'Меркурий', 'Луна') or _is_pair(a, 'Меркурий', 'Плутон') or _is_pair(a, 'Меркурий', 'Нептун')]
    if mental:
        a = min(mental, key=_orb)
        add(f'Разговоры здесь имеют особый вес: {_syn_label(a, n1, n2)}. Одной фразой можно быстро дать ощущение близости, но одной неудачной формулировкой — задеть. Особенно чувствительны переписка, обсуждение денег, верности, планов и фразы вроде «ты всегда» или «тебе всё равно»: в такой карте они могут запускать гораздо больший конфликт, чем сам первоначальный повод.')

    # Серьёзность и проверки.
    saturn = [a for a in aspects if 'Сатурн' in (a.get('person1_planet'), a.get('person2_planet'))]
    if saturn:
        a = min(saturn, key=_orb)
        add(f'В карте заметна тема ответственности: {_syn_label(a, n1, n2)}. Поэтому отношения проверяются поступками. Важными становятся не только слова о чувствах, но и то, кто выполняет обещания, как пара проходит период усталости, как распределяет деньги и обязанности и способен ли каждый оставаться надёжным, когда романтического настроения нет.')

