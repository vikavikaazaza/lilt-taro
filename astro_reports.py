def _pair_sentence(a: dict[str, Any], n1: str, n2: str, *, detail: bool = False) -> str:
    pair = _pair_key(a)
    base = _PAIR_TEXT.get(pair)
    if not base:
        p1 = str(a.get('person1_planet',''))
        p2 = str(a.get('person2_planet',''))
        base = f'Эта связь одновременно затрагивает {PLANET_ROLE.get(p1, "важную личную тему")} и {PLANET_ROLE.get(p2, "важную тему партнёра")}.'
    effect = _ASPECT_EFFECT.get(str(a.get('aspect','')), '')
    if not detail:
        return f'{base} {effect}'.strip()
    # Внутри одного отчёта одинаковая пара планет может встречаться несколько раз.
    # Поэтому для второго аспекта меняем акцент, а не повторяем абзац.
    p1, p2 = str(a.get('person1_planet','')), str(a.get('person2_planet',''))
    who1 = _name_case(n1, 'gen')
    who2 = _name_case(n2, 'gen')
    direction = f'Для {who1} эта связь сильнее затрагивает {_PLANET_TOPIC.get(p1, p1)}. Для {who2} она проявляется через {_PLANET_TOPIC.get(p2, p2)}.'
    return f'{base} {effect} {direction}'


def _rank_aspects(aspects: list[dict[str, Any]]) -> list[dict[str, Any]]:
    # Сначала самые точные связи, затем более слабые. При одинаковом орбе
    # выше поднимаем личные планеты.
    personal = {'Солнце':0,'Луна':0,'Меркурий':1,'Венера':1,'Марс':1,'Юпитер':2,'Сатурн':2,'Уран':3,'Нептун':3,'Плутон':3}
    def key(a):
        p1=str(a.get('person1_planet','')); p2=str(a.get('person2_planet',''))
        return (_orb(a), max(personal.get(p1,4),personal.get(p2,4)), p1, p2)
    return sorted(aspects, key=key)


def _unique_sentences(items: list[str], used: set[str], limit: int | None = None) -> list[str]:
    result=[]
    def words(text: str) -> set[str]:
        import re
        return {x for x in re.findall(r'[а-яёa-z0-9]+', text.lower()) if len(x)>3}
    used_sets=[words(x) for x in used]
    for item in items:
        for sentence in str(item).replace('\n',' ').split('. '):
            s=' '.join(sentence.strip().split())
            if not s:
                continue
            if s[-1] not in '.!?': s += '.'
            key=s.lower()
            w=words(s)
            if key in used or any((len(w & u) / max(1,min(len(w),len(u)))) >= 0.72 for u in used_sets if u):
                continue
            used.add(key); used_sets.append(w); result.append(s)
            if limit and len(result)>=limit:
                return result
    return result


