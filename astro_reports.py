def _syn_personal(a: dict[str, Any]) -> bool:
    """Убираем из клиентского текста чисто поколенческие связи.

    Например, Плутон–Плутон или Нептун–Нептун могут быть математически точными,
    но почти никогда не объясняют именно эту пару. Они только засоряют отчёт.
    """
    outer = {'Уран', 'Нептун', 'Плутон'}
    p1 = str(a.get('person1_planet', ''))
    p2 = str(a.get('person2_planet', ''))
    return not (p1 in outer and p2 in outer)



