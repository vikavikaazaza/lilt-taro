        horizons=[]
        for a in top:
            tp=str(a.get('transit_planet',''))
            if tp=='Луна': h='часы - 1 день'
            elif tp in {'Солнце','Меркурий','Венера','Марс'}: h='дни - несколько недель'
            elif tp in {'Юпитер','Сатурн'}: h='недели - месяцы'
            else: h='месяцы и дольше'
