def _transit_theme_paragraph(calc: dict[str, Any], aspects: list[dict[str, Any]]) -> list[tuple[str, str]]:
    out=[]
    top=aspects[:7]
    hard=[a for a in aspects if a.get('aspect') in {'Квадрат','Оппозиция'}]
    supportive=[a for a in aspects if a.get('aspect') in {'Тригон','Секстиль'}]
    long=[a for a in aspects if str(a.get('transit_planet')) in {'Юпитер','Сатурн','Уран','Нептун','Плутон'}]
    fast=[a for a in aspects if str(a.get('transit_planet')) in {'Солнце','Луна','Меркурий','Венера','Марс'}]

    if top:
        houses=[int(a['house']) for a in top if a.get('house')]
        main=[]
        if houses:
            c=Counter(houses)
            h=max(c,key=c.get)
            main.append(f'На первом плане находится сфера {HOUSE_THEME.get(h,"этой части жизни")}.')
        np=[str(a.get('natal_planet','')) for a in top[:4]]
        themes=[]
        if 'Солнце' in np: themes.append('личные цели и самоощущение')
        if 'Луна' in np: themes.append('эмоциональная безопасность и бытовые реакции')
        if 'Меркурий' in np: themes.append('разговоры, решения и документы')
        if 'Венера' in np: themes.append('отношения, деньги и личные ценности')
        if 'Марс' in np: themes.append('инициатива, скорость и границы')
        if 'Юпитер' in np: themes.append('рост и расширение возможностей')
        if 'Сатурн' in np: themes.append('обязательства, сроки и устойчивость')
        if themes: main.append('В этой зоне одновременно активны ' + ', '.join(themes[:3]) + '.')
        out.append(('1. Главная динамика дня', _join_sentences(main)))
    else:
        out.append(('1. Главная динамика дня','На выбранную дату сильных основных транзитных акцентов в заданных орбисах не найдено, поэтому конкретный событийный вывод лучше не делать.'))

    rel=[a for a in aspects if str(a.get('transit_planet')) in {'Венера','Марс','Юпитер','Уран','Нептун','Плутон'} or str(a.get('natal_planet')) in {'Венера','Марс','Солнце','Луна'}]
    r=[]
    rel_planets={str(a.get('transit_planet')) for a in rel}
    if 'Венера' in rel_planets: r.append('В отношениях заметнее становятся симпатия, встречи, желание сблизиться или вопросы взаимной ценности; при напряжении решения лучше не принимать из раздражения.')
    if 'Марс' in rel_planets: r.append('Может появиться желание быстро действовать и отстаивать границы; важно не превращать скорость в конфликт.')
    if 'Юпитер' in rel_planets: r.append('Открывается больше пространства для знакомств, полезных контактов, поездок и расширения круга общения.')
    if 'Уран' in rel_planets: r.append('Формат общения или отношений может неожиданно измениться, поэтому гибкость важнее попытки удержать старую схему.')
    if 'Нептун' in rel_planets: r.append('Романтические ожидания становятся тоньше, и полезно отделять интуицию от предположений.')
    if 'Плутон' in rel_planets: r.append('Взаимодействие переживается интенсивнее, поэтому особенно важны доверие и личные границы.')
    out.append(('2. Отношения и социальные события', _join_sentences(r[:3]) if r else 'Отдельного сильного акцента на отношениях и социальных контактах в выбранных орбисах нет.'))

    work=[a for a in aspects if str(a.get('transit_planet')) in {'Меркурий','Венера','Марс','Юпитер','Сатурн','Уран'} or str(a.get('natal_planet')) in {'Меркурий','Юпитер','Сатурн'}]
    w=[]; wp={str(a.get('transit_planet')) for a in work}
    if 'Меркурий' in wp: w.append('Подходящее поле для разговоров, документов, переговоров и пересмотра решений; важные детали стоит проверить перед отправкой.')
    if 'Венера' in wp: w.append('Можно решать вопросы денег, покупок и сотрудничества, но цену и условия лучше сверить без спешки.')
    if 'Марс' in wp: w.append('Есть энергия для запуска и выполнения задачи, но поспешность может создать лишний конфликт.')
    if 'Юпитер' in wp: w.append('Можно расширять план, искать полезный контакт, учиться или рассматривать новый вариант развития.')
    if 'Сатурн' in wp: w.append('Результат строится через дисциплину, сроки и проверку устойчивости.')
    if 'Уран' in wp: w.append('Рабочая схема или план может измениться неожиданно, поэтому полезно иметь запасной вариант.')
    work_houses=Counter(int(a['house']) for a in work if a.get('house'))
    if work_houses:
        h=max(work_houses,key=work_houses.get); w.append(f'Особое внимание стоит обратить на сферу {HOUSE_THEME.get(h,"активного дома")}.')
    out.append(('3. Работа, деньги, документы и решения', _join_sentences(w[:4]) if w else 'В выбранных орбисах нет отдельного сильного набора транзитов, который прямо акцентировал бы рабочие или финансовые вопросы.'))

    moon=[a for a in aspects if str(a.get('transit_planet'))=='Луна']
    if moon:
        emotion='Эмоциональный фон может быть более реактивным: легче заметить раздражение, чувствительность и быструю смену настроения.' if any(_polarity(str(a.get('aspect','')))=='hard' for a in moon) else 'Эмоциональный фон становится мягче и восприимчивее, легче заметить собственные потребности и найти то, что возвращает чувство комфорта.'
    else: emotion='Отдельного точного лунного акцента к натальным планетам в выбранных орбисах нет.'
