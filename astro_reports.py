    uranus = [a for a in aspects if _is_pair(a, 'Уран', 'Венера') or _is_pair(a, 'Уран', 'Меркурий') or _is_pair(a, 'Уран', 'Марс') or _is_pair(a, 'Уран', 'Солнце')]
    if uranus:
        a = min(uranus, key=_orb)
        add(f'Необычный элемент пары — {_syn_label(a, n1, n2)}. Отношениям нужен воздух: собственные интересы, друзья, отдельное время и ощущение свободы. При этом именно внезапность может поддерживать интерес — неожиданная поездка, новый план, спонтанная встреча или изменение привычного формата иногда сближает сильнее заранее расписанного сценария.')

    # Плутон.
    pluton = [a for a in aspects if 'Плутон' in (a.get('person1_planet'), a.get('person2_planet')) and (set((a.get('person1_planet'), a.get('person2_planet'))) & {'Луна','Венера','Марс','Меркурий','Солнце'})]
