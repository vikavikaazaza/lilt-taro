def build_transit_interpretation(calc: dict[str, Any]) -> str:
    aspects = sorted(list(calc.get('aspects', [])), key=_transit_sort_key)
    return '\n\n'.join(title + '\n' + body for title, body in _transit_narrative(calc, aspects))


def transit_pdf_sections(calc: dict[str, Any]) -> list[tuple[str, list[str]]]:
    aspects = sorted(list(calc.get('aspects', [])), key=_transit_sort_key)
    sections: list[tuple[str, list[str]]] = []
    sections.extend((title, [body]) for title, body in _transit_narrative(calc, aspects))
    sections.append(('Техническая таблица активных аспектов', [_transit_aspect_text(a) for a in aspects] or ['Значимых аспектов в заданных орбисах не найдено.']))
    return sections
