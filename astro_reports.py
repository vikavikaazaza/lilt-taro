    o.append('Если суммировать карту простым языком, это союз, которому особенно полезно сочетать близость и свободу, чувства и конкретику, романтику и бытовую договорённость. Чем меньше между вами недосказанности в действительно важных вопросах, тем больше энергии остаётся на саму близость.')
    out.append(('8. Общая картина', _join(o)))

    # 9. Final.
    f: list[str] = []
    if pair_exists('Меркурий', 'Нептун'):
        f.append('Одна из сильных сторон - ощущение интеллектуального и интуитивного контакта: вы можете давать друг другу чувство, что вас понимают глубже обычного.')
    if any(_is_pair(a, 'Луна', 'Венера') or _is_pair(a, 'Венера', 'Марс') or _is_pair(a, 'Солнце', 'Венера') for a in aspects):
        f.append('Романтическая часть имеет конкретную опору: есть эмоциональная симпатия, интерес и желание получать взаимный отклик.')
    if hard:
        f.append('Основная сложность связана не с отсутствием интереса, а с тем, как каждый реагирует на напряжение, различия и чувство уязвимости.')
    if pair_exists('Юпитер', 'Сатурн') or any('Сатурн' in _pair_key(a) for a in aspects) or angles['DSC']:
        f.append('Для долгой истории особенно важны ясные договорённости о деньгах, границах, бытовых обязанностях и будущем формате отношений.')
    f.append('Главный практический вывод простой: в этой паре качество отношений сильно зависит от того, насколько легко вы умеете переводить чувства в слова, слова - в договорённости, а договорённости - в реальные действия.')
    out.append(('9. Итог', _join(f)))
    return out


