def _transit_narrative(calc: dict[str, Any], aspects: list[dict[str, Any]]) -> list[tuple[str, str]]:
    """Структурный клиентский прогноз. Синастрию не затрагивает.
    Один аспект получает одну основную роль, а в тематических разделах
    используется только если действительно относится к этой сфере.
    """
    top = aspects[:6]
    out: list[tuple[str, str]] = []
    if not top:
        return [('1. Главный сюжет дня', 'Значимых активных связей немного. Дата скорее продолжает уже начатые процессы, чем создаёт отдельное событие.')]

    # --- 1. Главный сюжет: 2–3 ведущих аспекта складываются в одну цепочку.
    lead = top[:3]
    lead_events = [_transit_short_event(a) for a in lead]
    hcounts = Counter(_house(a) for a in lead if _house(a))
    focus = _transit_house_phrase(hcounts.most_common(1)[0][0]) if hcounts else ''
    first = 'В центре дня ' + lead_events[0].rstrip('.') + '.'
    second_parts = []
    if len(lead) > 1:
        second_parts.append('После этого ' + lead_events[1].lower().rstrip('.') + '.')
    if len(lead) > 2:
        second_parts.append('Дальше ситуация может перейти к следующему практическому шагу: ' + lead_events[2].lower().rstrip('.') + '.')
    if focus:
        second_parts.append(f'Основной фон даты связан со сферой {focus}.')
    out.append(('1. Главный сюжет дня', _join([first] + second_parts)))

    # --- 2. Конкретные события: уникальные сценарии, без повторения главного текста.
    scenarios: list[str] = []
    seen_keys: set[str] = set()
    for a in top:
        text = _transit_concrete_scene(a)
        key = re.sub(r'[^а-яё]+', ' ', text.lower()).strip()
        if key and key not in seen_keys:
            scenarios.append(text)
            seen_keys.add(key)
        if len(scenarios) >= 5:
            break
    out.append(('2. Что конкретно может произойти', _join(scenarios)))

    # Тематические аспекты выбираются отдельно. Главные 2–3 аспекта не копируем
    # целиком повторно: здесь они получают только другой угол проявления.
    rel = [a for a in top if 'relationship' in _transit_topics(a)]
    work = [a for a in top if {'work', 'money', 'documents'} & _transit_topics(a)]
    home = [a for a in top if 'home' in _transit_topics(a)]

    if rel:
        out.append(('3. Отношения и личная жизнь', _join([_transit_section_text(a, 'relationship') for a in rel[:2]])))
    else:
        out.append(('3. Отношения и личная жизнь', 'Личная жизнь не выглядит главным источником событий этой даты. Она скорее отреагирует на изменения в планах, настроении или занятости, чем сама станет центральной темой.'))

    if work:
        out.append(('4. Работа, деньги и документы', _join([_transit_section_text(a, 'work') for a in work[:3]])))

    if home:
        out.append(('5. Дом и эмоциональный фон', _join([_transit_section_text(a, 'home') for a in home[:2]])))

    hard = [a for a in top if _hard(a)]
    if hard:
        risks = []
        for a in hard[:3]:
            tp = str(a.get('transit_planet', ''))
            if tp == 'Марс':
                risks.append('резко ответить раньше, чем станет понятна вся ситуация')
            elif tp == 'Меркурий':
                risks.append('отправить письмо или согласовать условия, не перепроверив детали')
            elif tp in {'Уран', 'Плутон'}:
                risks.append('попытаться одним решением резко закрыть затянувшийся вопрос')
            elif tp == 'Сатурн':
                risks.append('взять на себя обязательство, не оценив сроки и нагрузку')
            else:
                risks.append('сделать окончательный вывод по первой эмоциональной реакции')
        out.append(('6. Где возможны сложности', 'Основные риски дня — ' + _join(risks)))

    supportive = [a for a in top if _supportive(a)]
    if supportive:
        actions = []
        for a in supportive[:3]:
            topics = _transit_topics(a)
            if 'documents' in topics:
                actions.append('отправить документ или зафиксировать договорённость')
            elif 'relationship' in topics:
                actions.append('назначить встречу и проговорить условия заранее')
            elif 'money' in topics:
                actions.append('сделать расчёт, покупку или финансовое решение после проверки суммы')
            elif 'work' in topics:
                actions.append('назначить срок и перевести рабочую идею в следующий этап')
            else:
                actions.append('сделать первый конкретный шаг по уже существующему плану')
        out.append(('7. Что стоит продвинуть', 'Лучше всего использовать поддерживающую часть дня для уже созревшего вопроса: ' + _join(actions)))

    timing = list(dict.fromkeys(_transit_timing(a) for a in top[:4]))
    out.append(('8. Когда ждать проявления', _join(timing)))

    tail = []
    if focus:
        tail.append(f'Главная сфера даты — {focus}.')
    if lead:
        tail.append('События разворачиваются не как отдельные случайности, а как цепочка: информация или повод → реакция → конкретное решение.')
    if hard:
        tail.append('Там, где ситуация требует выбора, лучше оставить небольшой запас времени между первой реакцией и окончательным решением.')
    out.append(('9. Итог', _join(tail) or 'Дата продолжает уже идущие процессы; наиболее заметными будут конкретные события из первых разделов.'))
    return out

def build_transit_interpretation(calc: dict[str, Any]) -> str:
    aspects = sorted(list(calc.get('aspects', [])), key=_transit_sort_key)
    return '\n\n'.join(title + '\n' + body for title, body in _transit_narrative(calc, aspects))


def _transit_aspect_text(a: dict[str, Any]) -> str:
    return (
        f"{a.get('transit_planet', '')} {a.get('aspect', '')} натальному {a.get('natal_planet', '')}; "
        f"орб {a.get('orb_text', '')}; состояние: {a.get('state', '')}; "
        f"дом: {a.get('house') or 'не определён'}"
    )


def transit_pdf_sections(calc: dict[str, Any]) -> list[tuple[str, list[str]]]:
    aspects = sorted(list(calc.get('aspects', [])), key=_transit_sort_key)
    sections = [(title, [body]) for title, body in _transit_narrative(calc, aspects)]
    sections.append(
        ('Техническая таблица активных аспектов',
         [_transit_aspect_text(a) for a in aspects] or ['Значимых аспектов в заданных орбисах не найдено.'])
    )
    return sections


