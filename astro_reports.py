def _join_sentences(items: list[str]) -> str:
    clean = []
    seen = set()
    for x in items:
        x = ' '.join(str(x).split()).strip()
        if not x:
            continue
        if x[-1] not in '.!?':
            x += '.'
        key = x.lower()
        if key not in seen:
            clean.append(x)
            seen.add(key)
    return ' '.join(clean)


