    aspects = _rank_aspects(list(calc.get('aspects', [])))
    hard = [a for a in aspects if _hard(a)]
    supportive = [a for a in aspects if _supportive(a)]
    overlays = _overlay_map(calc)
    used: set[str] = set()
    out=[]

    # 1. Главная динамика — только самые сильные и разные связи.
    lead=[]; pairs=set()
    for a in aspects:
        pair=_pair_key(a)
        if pair in pairs: continue
        lead.append(a); pairs.add(pair)
        if len(lead)>=5: break
    p=[]
    for a in lead:
        p.append(_pair_sentence(a,n1,n2,detail=True))
    if hard:
        p.append('Напряжение в этой карте не является отдельной темой само по себе: оно появляется там, где конкретные желания двух людей сталкиваются.')
