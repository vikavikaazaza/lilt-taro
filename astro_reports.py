def _syn_scenario_list(aspects: list[dict[str, Any]], n1: str, n2: str) -> list[str]:
    """Раздел 7 строится из конкретных связей этой карты, а не из общего набора абзацев."""
    out: list[str] = []
    used: set[str] = set()
    ranked = sorted(aspects, key=_syn_aspect_priority)

    def add(text: str) -> None:
        text = ' '.join(text.split()).strip()
        if text and text.lower() not in used:
            out.append(text if text[-1] in '.!?' else text + '.')
            used.add(text.lower())

    # Берём разные типы связей, а не несколько аспектов одного типа подряд.
    selected: list[dict[str, Any]] = []
    seen_pairs: set[frozenset[str]] = set()
    for a in ranked:
        pair = _pair_key(a)
        if pair in seen_pairs:
            continue
        selected.append(a)
        seen_pairs.add(pair)
        if len(selected) >= 5:
            break

    for a in selected:
        add(_syn_plain_meaning(a, n1, n2))

    # Добавляем один действительно индивидуальный бытовой сюжет по домам.
    overlays = _overlay_map({'overlays_1_in_2': [], 'overlays_2_in_1': []})
    # В этом месте вызывающий код передаёт только аспекты, поэтому домовые данные
    # добавляются в _syn_narrative отдельно. Здесь оставляем только аспектные сцены.
    if not out:
        add(f'Для {_name_case(n1,"gen")} и {_name_case(n2,"gen")} самые показательные моменты будут возникать там, где нужно одновременно учитывать желания обоих. Особенно многое станет понятно по деньгам, времени, личному пространству и совместным планам.')
    return out[:5]


