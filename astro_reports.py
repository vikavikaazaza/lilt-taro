def _transit_scenario(a: dict[str, Any]) -> str:
    tp = str(a.get('transit_planet', ''))
    np = str(a.get('natal_planet', ''))
    hard = _hard(a)
    asp = str(a.get('aspect', ''))

    if tp == 'Марс' and np in {'Венера', 'Луна', 'Марс'}:
        text = 'Вероятен конкретный повод для действия: встреча, выяснение отношений, покупка, решение по деньгам или ситуация, где придётся быстро отреагировать.'
    elif tp == 'Венера' and np in {'Луна', 'Венера', 'Солнце', 'Марс'}:
        text = 'Вероятен заметный контакт с темой симпатии, встречи, денег или удовольствия: приятное предложение, свидание, покупка или разговор о чувствах.'
    elif tp == 'Меркурий':
        text = 'Вероятен информационный повод: сообщение, звонок, документ, поездка, согласование или возвращение к вопросу, который ещё не закрыт.'
    elif tp == 'Юпитер':
        text = 'Вероятен шанс расширить уже существующую ситуацию: предложение, обучение, поездка, полезное знакомство или новый проект.'
    elif tp == 'Сатурн':
        text = 'Вероятнее не внезапное событие, а конкретная проверка реальностью: срок, обязанность, документ, финансовое решение или необходимость определить границу.'
    elif tp == 'Уран':
        text = 'Вероятен неожиданный поворот: изменение планов, новая информация, внезапное предложение или решение сделать по-другому.'
