def build_synastry_interpretation(calc: dict[str, Any]) -> str:
    return '\n\n'.join(title + '\n' + body for title, body in _syn_narrative_long(calc))


def _pair_technical(a: dict[str, Any], n1: str, n2: str) -> str:
    p1, p2 = str(a['person1_planet']), str(a['person2_planet'])
    return f'{n1}: {p1} ({a.get("person1_sign", "")} {a.get("person1_position", "")}) {a.get("aspect", "")} {n2}: {p2} ({a.get("person2_sign", "")} {a.get("person2_position", "")}); орб {a.get("orb_text", "")}; {a.get("relationship_weight", "")}'


def synastry_pdf_sections(calc: dict[str, Any]) -> list[tuple[str, list[str]]]:
    n1, n2 = _name(calc, 1), _name(calc, 2)
    aspects = sorted(list(calc.get('aspects', [])), key=_aspect_sort_key)
    sections: list[tuple[str, list[str]]] = []
    sections.extend((title, [body]) for title, body in _syn_narrative_long(calc))
    sections.append(('Техническая таблица аспектов', [_pair_technical(a, n1, n2) for a in aspects] or ['Значимых межпланетных аспектов в заданных орбисах не найдено.']))
    return sections


