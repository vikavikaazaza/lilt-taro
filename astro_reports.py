def build_synastry_aspect_detail(a: dict[str, Any], name1: str = '', name2: str = '', seen_topics=None, index: int | None = None) -> dict[str, Any]:
    """Return the structured text used by the Mini App for one synastry aspect."""
    n1 = name1 or str(a.get('name1') or 'Первого человека')
    n2 = name2 or str(a.get('name2') or 'Второго человека')
    text = _aspect_human(a, n1, n2)
    pair = _pair_key(a)
    aspect = str(a.get('aspect') or '')
    topics = []
    if any(x in pair for x in ('Луна', 'Венера')): topics.append('чувства и близость')
