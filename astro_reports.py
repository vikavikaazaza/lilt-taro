def _name(calc: dict[str, Any], idx: int) -> str:
    return str(calc.get(f'name{idx}') or f'Человек {idx}')


def _name_case(name: str, case: str) -> str:
    raw = ' '.join(str(name or '').split()).strip()
    if not raw or case not in {'gen', 'ins'}:
        return raw
    first, *rest = raw.split()
    forms = _NAME_CASES.get(first.lower())
    if not forms:
        return raw
    return ' '.join([forms[0] if case == 'gen' else forms[1], *rest])


def _orb(a: dict[str, Any], default: float = 99.0) -> float:
    try:
        return float(a.get('orb', default))
    except Exception:
        return default


def _aspect_sort_key(a: dict[str, Any]) -> tuple[float, str, str]:
    return _orb(a), str(a.get('person1_planet', '')), str(a.get('person2_planet', ''))


def _transit_sort_key(a: dict[str, Any]) -> tuple[float, str, str]:
    return _orb(a), str(a.get('transit_planet', '')), str(a.get('natal_planet', ''))


def _pair_key(a: dict[str, Any]) -> frozenset[str]:
    return frozenset((str(a.get('person1_planet', '')), str(a.get('person2_planet', ''))))


def _pair(left: str, right: str) -> frozenset[str]:
    return frozenset((left, right))


def _is_pair(a: dict[str, Any], left: str, right: str) -> bool:
    return _pair_key(a) == _pair(left, right)


def _hard(a: dict[str, Any]) -> bool:
    return str(a.get('aspect', '')) in {'Квадрат', 'Оппозиция'}


def _supportive(a: dict[str, Any]) -> bool:
    return str(a.get('aspect', '')) in {'Тригон', 'Секстиль', 'Соединение'}


def _join(items: list[str]) -> str:
    out: list[str] = []
    seen: set[str] = set()
    for item in items:
        text = ' '.join(str(item).split()).strip()
        if not text:
            continue
        if text[-1] not in '.!?':
            text += '.'
        key = text.lower()
        if key not in seen:
            out.append(text)
            seen.add(key)
    return ' '.join(out)


def _angle_points(calc: dict[str, Any]) -> dict[str, list[dict[str, Any]]]:
    out = {'ASC': [], 'DSC': [], 'MC': [], 'IC': []}
    for a in calc.get('angle_aspects', []):
        point = str(a.get('point', ''))
        if point in out:
            out[point].append(a)
    return out


def _overlay_map(calc: dict[str, Any]) -> dict[tuple[int, int], list[str]]:
    out: dict[tuple[int, int], list[str]] = {}
    for x in calc.get('overlays_1_in_2', []):
        h = int(x.get('house', 0) or 0)
        if h:
            out.setdefault((2, h), []).append(str(x.get('planet', '')))
    for x in calc.get('overlays_2_in_1', []):
        h = int(x.get('house', 0) or 0)
        if h:
            out.setdefault((1, h), []).append(str(x.get('planet', '')))
    return out


