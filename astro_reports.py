def _transit_concrete_scene(a: dict[str, Any]) -> str:
    tp = str(a.get('transit_planet', ''))
    np = str(a.get('natal_planet', ''))
    h = _house(a)
    if (tp, np) in {('Марс','Луна'), ('Меркурий','Луна')}:
        return 'Кто-то может изменить договорённость по дому, опоздать или поднять старый семейный вопрос — и разговор быстро станет принципиальным.'
    if (tp, np) in {('Марс','Меркурий'), ('Меркурий','Меркурий')}:
        return 'Практический повод может прийти через звонок, письмо, перенос поездки или документ, который придётся перечитать и подтвердить.'
    if (tp, np) in {('Марс','Венера'), ('Венера','Марс')}:
        return 'Возможны внезапное приглашение, изменение планов встречи или разговор о том, сколько внимания и времени каждый готов вкладывать.'
    if (tp, np) in {('Сатурн','Меркурий'), ('Сатурн','Солнце')}:
        return 'Может потребоваться поставить дату, подписать документ, выполнить обещание или закрыть задачу, которую долго переносили.'
    if (tp, np) in {('Уран','Солнце'), ('Уран','Венера')}:
        return 'Один из привычных вариантов может отпасть: переносится встреча, меняется график, появляется другой человек или новое предложение.'
    if (tp, np) in {('Плутон','Венера'), ('Плутон','Солнце')}:
        return 'Небольшой повод способен вывести на разговор о контроле, доверии, деньгах или личных границах — и после него прежняя схема уже не будет устраивать.'
    if h == 2:
        return 'Вероятен конкретный финансовый повод: оплата, покупка, перерасчёт суммы или обсуждение того, кто и за что платит.'
    if h == 3:
        return 'Событие может быть связано с сообщением, документом, короткой поездкой или необходимостью быстро согласовать детали.'
    if h == 4:
        return 'Домашний вопрос может потребовать решения: покупка, ремонт, распределение обязанностей, визит родственника или изменение бытового плана.'
    if h == 5:
        return 'Повод может прийти через свидание, детей, творчество, праздник или желание наконец выделить время на приятное дело.'
    if h == 6:
        return 'Рабочая рутина может измениться из-за срочной задачи, нового графика, перераспределения обязанностей или необходимости закрыть хвост.'
    if h == 7:
        return 'Партнёрская договорённость может потребовать конкретики: встреча, срок, обещание, распределение расходов или решение о дальнейшем формате.'
    if h == 8:
        return 'Может возникнуть разговор об общей сумме, долге, доверии или вопросе, который обычно не обсуждают вслух.'
    if h == 9:
        return 'Возможен повод, связанный с поездкой, обучением, документами или планом, который открывает следующий этап.'
    if h == 10:
        return 'Рабочий результат может потребовать публичного решения: согласовать срок, показать готовый результат или принять новую ответственность.'
    if h == 11:
        return 'Изменение может прийти через друзей, команду, сообщество или совместный проект — например, меняется роль или общий план.'
    return 'Один из уже существующих вопросов получит конкретный повод для движения: сообщение, встречу, оплату, перенос или решение.'


def _transit_section_text(a: dict[str, Any], section: str) -> str:
    """Переводит один аспект в другую жизненную плоскость, не копируя его
    основной сценарий дословно.
    """
    tp = str(a.get('transit_planet', ''))
    np = str(a.get('natal_planet', ''))
    h = _house(a)
    hard = _hard(a)
    if section == 'relationship':
        if tp == 'Марс' or np == 'Марс':
            return 'В отношениях это скорее проявится через инициативу и проверку границ: кто первым пишет, предлагает встречу, меняет планы или требует ясного ответа.'
        if tp == 'Венера' or np == 'Венера':
            return 'Личная жизнь может дать приятный повод для контакта: встречу, признание симпатии, обсуждение денег или переход к более понятному формату отношений.'
        if tp == 'Уран' or np == 'Уран':
            return 'Привычный формат общения способен измениться: встреча переносится, появляется неожиданный вариант или человек неожиданно обозначает своё желание.'
        if tp == 'Сатурн' or np == 'Сатурн':
            return 'В отношениях на первый план выходит определённость: статус, обещание, срок, совместная ответственность или необходимость договориться о правилах.'
        return 'Событие затрагивает отношения косвенно: через настроение, разговор, планы или необходимость согласовать ожидания.'

    if section == 'work':
        if h in {2, 8}:
            return 'В финансовой части это может быть пересмотр суммы, оплаты, общей покупки или условий, которые раньше оставались неоговорёнными.'
        if tp == 'Меркурий' or np == 'Меркурий' or h in {3, 9}:
            return 'В делах вероятны письмо, согласование, документ, поездка или повторное обсуждение условий; важным становится конкретный срок и подтверждение договорённости.'
        if tp == 'Сатурн' or np == 'Сатурн':
            return 'Рабочий вопрос потребует результата, а не обсуждения: закрыть задачу, оформить документ, назначить срок или распределить ответственность.'
        if tp in {'Юпитер', 'Уран'} or np in {'Юпитер', 'Уран'}:
            return 'В работе может появиться новый вариант: другой график, предложение, обучение, новый формат сотрудничества или изменение текущего плана.'
        return 'В рабочих делах лучше переводить возникший повод в конкретный результат: договорённость, срок, оплату или следующий этап.'

    if section == 'home':
        if tp == 'Марс' or np == 'Марс':
            return 'Дома напряжение скорее выйдет через мелочь — опоздание, бытовую обязанность, деньги или нарушение личного пространства, которое окажется последней каплей.'
        if tp == 'Меркурий' or np == 'Меркурий':
            return 'В семье разговор может вернуть старую тему: кто что делает, когда встречаетесь, что покупаете или какое решение уже нельзя откладывать.'
        if tp == 'Венера':
            return 'Бытовая сторона дня может стать мягче: совместная покупка, забота, приятное изменение дома или спокойный разговор с близким.'
        return 'Эмоциональный фон сильнее зависит от того, насколько понятны домашние договорённости и личное пространство.'

    return _transit_short_event(a)


def _transit_narrative(calc: dict[str, Any], aspects: list[dict[str, Any]]) -> list[tuple[str, str]]:
    """Структурный клиентский прогноз. Синастрию не затрагивает.
    Один аспект получает одну основную роль, а в тематических разделах
    используется только если действительно относится к этой сфере.
    """
    top = aspects[:6]
    out: list[tuple[str, str]] = []
    if not top:
        return [('1. Главный сюжет дня', 'Значимых активных связей немного. Дата скорее продолжает уже начатые процессы, чем создаёт отдельное событие.')]

    # --- 1. Главный сюжет: 2–3 ведущих аспекта складываются в одну цепочку.
    lead = top[:3]
    lead_events = [_transit_short_event(a) for a in lead]
    hcounts = Counter(_house(a) for a in lead if _house(a))
    focus = _transit_house_phrase(hcounts.most_common(1)[0][0]) if hcounts else ''
    first = 'В центре дня ' + lead_events[0].rstrip('.') + '.'
    second_parts = []
    if len(lead) > 1:
        second_parts.append('После этого ' + lead_events[1].lower().rstrip('.') + '.')
    if len(lead) > 2:
        second_parts.append('Дальше ситуация может перейти к следующему практическому шагу: ' + lead_events[2].lower().rstrip('.') + '.')
    if focus:
        second_parts.append(f'Основной фон даты связан со сферой {focus}.')
    out.append(('1. Главный сюжет дня', _join([first] + second_parts)))

    # --- 2. Конкретные события: уникальные сценарии, без повторения главного текста.
    scenarios: list[str] = []
    seen_keys: set[str] = set()
    for a in top:
        text = _transit_concrete_scene(a)
        key = re.sub(r'[^а-яё]+', ' ', text.lower()).strip()
        if key and key not in seen_keys:
            scenarios.append(text)
            seen_keys.add(key)
        if len(scenarios) >= 5:
            break
    out.append(('2. Что конкретно может произойти', _join(scenarios)))

    # Тематические аспекты выбираются отдельно. Главные 2–3 аспекта не копируем
    # целиком повторно: здесь они получают только другой угол проявления.
    rel = [a for a in top if 'relationship' in _transit_topics(a)]
    work = [a for a in top if {'work', 'money', 'documents'} & _transit_topics(a)]
    home = [a for a in top if 'home' in _transit_topics(a)]

    if rel:
        out.append(('3. Отношения и личная жизнь', _join([_transit_section_text(a, 'relationship') for a in rel[:2]])))
    else:
        out.append(('3. Отношения и личная жизнь', 'Личная жизнь не выглядит главным источником событий этой даты. Она скорее отреагирует на изменения в планах, настроении или занятости, чем сама станет центральной темой.'))

    if work:
        out.append(('4. Работа, деньги и документы', _join([_transit_section_text(a, 'work') for a in work[:3]])))

    if home:
        out.append(('5. Дом и эмоциональный фон', _join([_transit_section_text(a, 'home') for a in home[:2]])))

    hard = [a for a in top if _hard(a)]
    if hard:
        risks = []
        for a in hard[:3]:
            tp = str(a.get('transit_planet', ''))
            if tp == 'Марс':
                risks.append('резко ответить раньше, чем станет понятна вся ситуация')
            elif tp == 'Меркурий':
                risks.append('отправить письмо или согласовать условия, не перепроверив детали')
            elif tp in {'Уран', 'Плутон'}:
                risks.append('попытаться одним решением резко закрыть затянувшийся вопрос')
            elif tp == 'Сатурн':
                risks.append('взять на себя обязательство, не оценив сроки и нагрузку')
            else:
                risks.append('сделать окончательный вывод по первой эмоциональной реакции')
        out.append(('6. Где возможны сложности', 'Основные риски дня — ' + _join(risks)))

    supportive = [a for a in top if _supportive(a)]
    if supportive:
        actions = []
        for a in supportive[:3]:
            topics = _transit_topics(a)
            if 'documents' in topics:
                actions.append('отправить документ или зафиксировать договорённость')
            elif 'relationship' in topics:
                actions.append('назначить встречу и проговорить условия заранее')
            elif 'money' in topics:
                actions.append('сделать расчёт, покупку или финансовое решение после проверки суммы')
            elif 'work' in topics:
                actions.append('назначить срок и перевести рабочую идею в следующий этап')
            else:
                actions.append('сделать первый конкретный шаг по уже существующему плану')
        out.append(('7. Что стоит продвинуть', 'Лучше всего использовать поддерживающую часть дня для уже созревшего вопроса: ' + _join(actions)))

    timing = list(dict.fromkeys(_transit_timing(a) for a in top[:4]))
    out.append(('8. Когда ждать проявления', _join(timing)))

    tail = []
    if focus:
        tail.append(f'Главная сфера даты — {focus}.')
    if lead:
        tail.append('События разворачиваются не как отдельные случайности, а как цепочка: информация или повод → реакция → конкретное решение.')
    if hard:
        tail.append('Там, где ситуация требует выбора, лучше оставить небольшой запас времени между первой реакцией и окончательным решением.')
    out.append(('9. Итог', _join(tail) or 'Дата продолжает уже идущие процессы; наиболее заметными будут конкретные события из первых разделов.'))
    return out

def build_transit_interpretation(calc: dict[str, Any]) -> str:
    aspects = sorted(list(calc.get('aspects', [])), key=_transit_sort_key)
    return '\n\n'.join(title + '\n' + body for title, body in _transit_narrative(calc, aspects))


def _transit_aspect_text(a: dict[str, Any]) -> str:
    return (
        f"{a.get('transit_planet', '')} {a.get('aspect', '')} натальному {a.get('natal_planet', '')}; "
        f"орб {a.get('orb_text', '')}; состояние: {a.get('state', '')}; "
        f"дом: {a.get('house') or 'не определён'}"
    )


def transit_pdf_sections(calc: dict[str, Any]) -> list[tuple[str, list[str]]]:
    aspects = sorted(list(calc.get('aspects', [])), key=_transit_sort_key)
    sections = [(title, [body]) for title, body in _transit_narrative(calc, aspects)]
    sections.append(
        ('Техническая таблица активных аспектов',
         [_transit_aspect_text(a) for a in aspects] or ['Значимых аспектов в заданных орбисах не найдено.'])
    )
    return sections


