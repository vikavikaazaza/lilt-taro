def _transit_topics(a: dict[str, Any]) -> set[str]:
    """Семантические метки аспекта. Нужны, чтобы один и тот же аспект
    не растаскивался одинаковым текстом по всем разделам.
    """
    tp = str(a.get('transit_planet', ''))
    np = str(a.get('natal_planet', ''))
    h = _house(a)
    topics: set[str] = set()

    if h in {2, 8} or tp in {'Венера', 'Юпитер'} or np in {'Венера', 'Юпитер'}:
        topics.add('money')
    if h in {3, 9} or tp == 'Меркурий' or np == 'Меркурий':
        topics.add('documents')
    if h in {6, 10, 11} or tp in {'Сатурн', 'Юпитер', 'Уран'} or np in {'Сатурн', 'Юпитер', 'Уран'}:
        topics.add('work')
    if h in {4, 12} or np == 'Луна':
        topics.add('home')
    if h in {5, 7, 8} or tp in {'Венера', 'Марс'} or np in {'Венера', 'Марс'}:
        topics.add('relationship')
    if tp in {'Марс', 'Уран', 'Плутон'} or np in {'Марс', 'Уран', 'Плутон'} or _hard(a):
        topics.add('tension')
    if _supportive(a):
        topics.add('support')
    return topics


