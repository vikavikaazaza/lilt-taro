    conflicts = _syn_unique_aspects(conflicts, used)[:4]
    c = [[
        'За ссорой не всегда стоит сама причина. Часто за ней прячутся усталость, ревность, страх, обида или ощущение давления.',
        'Конфликт лучше разбирать глубже первой претензии. За резкими словами может стоять простое желание быть услышанным.',
        'Мелочь легко становится большой ссорой, если к ней уже добавились усталость, тревога или старые обиды.',
    ][len(aspects) % 3]]
    for i, a in enumerate(conflicts):
        c.append(_syn_aspect_story(a, i + 3))
    if conflicts:
        c.append('Если переписка внезапно становится резкой, лучше продолжить разговор голосом или лично: интонацию в сообщениях легко прочитать неправильно.')
    else:
        c.append([
            'Одна постоянная причина ссор здесь не выделяется. Полезнее разбирать каждый конфликт по фактам, а не переносить старые обиды на новый повод.',
            'Конфликты здесь не сводятся к одной схеме. После ссоры помогает отделить то, что произошло сейчас, от того, что накопилось раньше.',
            'Явного одного источника напряжения нет. Поэтому особенно важно называть конкретную проблему, а не собирать в неё всё сразу.',
        ][len(aspects) % 3])
    out.append(('4. Конфликты, ревность и болезненные точки', _join(c)))

    # 5. Дома: каждое наложение описывается один раз.
    practical: list[str] = []
    house_seen: set[tuple[int, int]] = set()
    for key, planets in sorted(overlays.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        target_idx, house = key
        if house < 2 or house > 12 or key in house_seen:
            continue
        house_seen.add(key)
        target = n1 if target_idx == 1 else n2
        practical.append(_syn_house_story(target, house))
        if len(practical) >= 6:
            break
    if not practical:
        practical.append('Отдельного сильного акцента по домам нет, поэтому бытовая сторона отношений больше зависит от самих аспектов и реальной жизни пары.')
    out.append(('5. Совместная жизнь, деньги и личное пространство', _join(practical)))

    # 6. Остаток аспектов. Здесь уже не должны повторяться связи из 1–4.
    remaining = [a for a in aspects if _pair_key(a) not in used]
    remaining = _syn_unique_aspects(remaining, used)[:7]
    d = [[
        'Здесь остаются детали, которые добавляют отношениям индивидуальность и объясняют, почему похожие ситуации вы иногда чувствуете по-разному.',
        'Этот раздел — про нюансы пары: именно они часто объясняют неожиданные реакции и разницу в подходах.',
        'Здесь собраны детали, которые дополняют основную картину и делают её более похожей именно на вашу пару.',
    ][len(aspects) % 3]]
    for i, a in enumerate(remaining):
        d.append(_syn_aspect_story(a, i + 5))
    if not remaining:
        pair_list = []
        for a in aspects:
            pair = tuple(sorted(_pair_key(a)))
            if pair not in pair_list:
                pair_list.append(pair)
        if len(pair_list) >= 2:
            p_left = pair_list[0]
            p_right = pair_list[1]
            left = ', а также '.join('«' + _SYN_ROLE_NOUN.get(x, 'важная тема') + '»' for x in p_left)
            right = ', а также '.join('«' + _SYN_ROLE_NOUN.get(x, 'другая тема') + '»' for x in p_right)
            d.append([
                f'Здесь встречаются две разные линии: {left} и {right}. Их сочетание объясняет, почему одна ситуация может давать совсем разные реакции.',
                f'Одна линия связана с темами {left}, другая — с {right}. Поэтому отношения могут одновременно давать интерес и требовать терпения.',
                f'В паре заметны две линии: {left} с одной стороны и {right} с другой. Именно их сочетание добавляет отношениям характер.',
                f'Здесь работают сразу две линии: {left} и {right}. Они включаются в разных обстоятельствах, поэтому реакция пары не всегда предсказуема.',
                f'Особенность пары — сочетание тем {left} и {right}. Именно это делает динамику более индивидуальной.',
            ][len(aspects) % 5])
            d.append([
                f'Особенно заметно это там, где нужно одновременно учитывать {left} и {right}. Лучше сначала обсудить решение, а потом действовать.',
                f'В жизни это может проявиться, когда приходится выбирать между привычным вариантом и новым.',
                f'Поэтому простой вопрос иногда затрагивает намного больше чувств и интересов, чем кажется вначале.',
                f'Здесь помогает разделить ситуацию на две части: что каждый хочет сейчас и что важно сохранить между вами.',
                f'В такой момент полезно не спешить с выводами и сначала спросить, что каждый действительно имеет в виду.',
            ][(len(aspects) + 1) % 5])
        elif pair_list:
            d.append(f'В этой карте особенно заметна связка {" и ".join(pair_list[0])}. Её стоит смотреть вместе с домами и реальными обстоятельствами пары.')
        else:
            d.append('Отдельных связей немного, поэтому важнее смотреть на общую динамику и реальные поступки партнёров.')
    out.append(('6. Что особенно важно именно в этой паре', _join(d)))

    # 7. Сценарии строятся из конкретных домов/углов, без повторения самих описаний домов.
    scenarios: list[str] = []
    for point in ('ASC', 'DSC', 'MC', 'IC'):
        if angles.get(point):
            if point == 'ASC':
                scenarios.append('Реакция друг на друга может быть очень быстрой: голос, взгляд, манера поведения и настроение сразу дают отклик.')
            elif point == 'DSC':
                scenarios.append('Партнёр может сильно менять ваше представление о том, какие отношения вам нужны и кто должен быть рядом.')
            elif point == 'MC':
                scenarios.append('Отношения могут влиять на карьерные планы и большие решения. Важный шаг часто хочется сначала обсудить с партнёром.')
            elif point == 'IC':
                scenarios.append('Дом и чувство безопасности могут быстро становиться общей темой. Жильё, семья и личное пространство здесь особенно важны.')
    used_scenario_houses: set[int] = set()
    for (target_idx, house), _ in sorted(overlays.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        if house in used_scenario_houses or house < 2 or house > 12:
            continue
        used_scenario_houses.add(house)
        scenarios.append(_syn_house_scenario(house))
        if len(scenarios) >= 5:
            break
    if not scenarios:
        scenarios.append('Многое будет видно в обычных вещах: встречах, деньгах, планах, личном пространстве и том, как вы возвращаетесь к разговору после ссоры.')
    out.append(('7. Что реально может происходить между вами', _join(scenarios[:5])))

    # 8. Длинная дистанция — только действительно присутствующие показатели.
    longterm: list[str] = []
    if any(_is_pair(a, 'Сатурн', 'Венера') for a in aspects):
        longterm.append('Для долгих отношений особенно важны надёжность и выполненные обещания. Главное — чтобы ответственность не вытесняла тепло.')
    if any(_is_pair(a, 'Юпитер', 'Сатурн') for a in aspects):
        longterm.append('Большие планы лучше выдерживают реальность, когда есть сроки, бюджет и понятный вклад каждого.')
    if any(_is_pair(a, 'Сатурн', 'Уран') for a in aspects):
        longterm.append('Свобода и стабильность могут периодически спорить между собой. Полезно заранее обсуждать правила, которые можно менять.')
    if any(_is_pair(a, 'Сатурн', 'Плутон') for a in aspects) or any(_is_pair(a, 'Венера', 'Плутон') for a in aspects):
        longterm.append('Чем серьёзнее отношения, тем важнее говорить о страхе потери и ревности прямо, без проверок и давления.')
    if any(h == 4 for (_, h) in overlays) or angles['IC']:
        longterm.append('Общий дом со временем становится отдельной частью отношений. Быт и семейные правила лучше обсуждать заранее.')
    if any(h == 7 for (_, h) in overlays) or angles['DSC']:
        longterm.append('Со временем особенно важны ясные правила пары: что для вас отношения, какие есть обязательства и чего вы ждёте друг от друга.')
    if not longterm:
        longterm.append('На длинной дистанции всё проверяет обычная жизнь: деньги, быт, планы, личное пространство и умение возвращаться к разговору после ссоры.')
    out.append(('8. Что происходит с отношениями на длинной дистанции', _join(longterm)))

