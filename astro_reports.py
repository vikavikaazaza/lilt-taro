    if any(p in pairs for p in {_pair('Уран','Солнце'),_pair('Уран','Венера'),_pair('Уран','Марс'),_pair('Уран','Сатурн')}):
        long.append('Связи с Ураном требуют пространства. Долгие отношения здесь легче сохраняют интерес, если у каждого остаются свои занятия и возможность иногда менять привычный сценарий.')
    if any(p in pairs for p in {_pair('Плутон','Венера'),_pair('Плутон','Луна'),_pair('Плутон','Марс'),_pair('Плутон','Солнце')}):
        long.append('Со временем особенно важной становится тема доверия. Если тревога превращается в контроль, связь устаёт; если о страхах можно говорить прямо, сильная привязанность становится опорой.')
