        _pair('Марс','Плутон'), _pair('Венера','Плутон'), _pair('Марс','Сатурн'),
        _pair('Меркурий','Венера'), _pair('Меркурий','Плутон'), _pair('Меркурий','Нептун'),
        _pair('Уран','Венера'), _pair('Сатурн','Венера'), _pair('Юпитер','Сатурн'),
