def build_synastry_interpretation(calc: dict[str, Any]) -> str:
    return '\n\n'.join(title + '\n' + text for title, text in _syn_narrative(calc))


def synastry_pdf_sections(calc: dict[str, Any]) -> list[tuple[str, list[str]]]:
    n1, n2 = _name(calc, 1), _name(calc, 2)
    p1, p2 = calc.get('person1', {}), calc.get('person2', {})
    aspects = sorted(list(calc.get('aspects', [])), key=_aspect_sort_key)
    sections: list[tuple[str, list[str]]] = []

    sections.append(('Исходные данные', [
        f'{n1}: {p1.get("birth_date", "")} | {p1.get("birth_time") or "время неизвестно"} | {p1.get("city", "")} | {p1.get("timezone", "")}',
        f'{n2}: {p2.get("birth_date", "")} | {p2.get("birth_time") or "время неизвестно"} | {p2.get("city", "")} | {p2.get("timezone", "")}',
        f'Межпланетных аспектов: {len(aspects)}; аспектов к углам: {len(calc.get("angle_aspects", []))}',
        'Основной текст ниже собран в цельные блоки по темам. Технический список аспектов оставлен отдельно в конце отчёта.',
    ]))

    def planet_lines(person: dict[str, Any]) -> list[str]:
        lines = []
        for planet, data in person.get('planets', {}).items():
            retro = ' | ретроградное' if data.get('retrograde') else ''
            lines.append(f'{planet}: {data.get("sign", "")} {data.get("position", "")}{retro}')
        if person.get('time_known'):
            lines.append(f'ASC: {person.get("ascendant_sign", "")}')
            lines.append(f'MC: {person.get("mc_sign", "")}')
        return lines
    sections.append((f'Натальные положения - {n1}', planet_lines(p1)))
    sections.append((f'Натальные положения - {n2}', planet_lines(p2)))

    # Cohesive prose blocks: exactly one paragraph in each thematic section.
    sections.extend((title, [text]) for title, text in _syn_narrative(calc))

    # Technical appendix: aspects, angles, houses - keep the exact calculations visible.
    sections.append(('Техническая таблица аспектов', [_pair_technical(a, n1, n2) for a in aspects] or ['Значимых межпланетных аспектов в заданных орбисах не найдено.']))
    angle_items = sorted(calc.get('angle_aspects', []), key=lambda x: float(x.get('orb', 99)))
    sections.append(('Технические связи с ASC / DSC / MC / IC', [_angle_text(a, calc) for a in angle_items] or ['Аспекты к углам не найдены или дома недоступны.']))

    overlays = []
    overlays.extend(_house_overlay_text(x, n1, n2) for x in calc.get('overlays_1_in_2', []))
    overlays.extend(_house_overlay_text(x, n2, n1) for x in calc.get('overlays_2_in_1', []))
    sections.append(('Техническая таблица планет в домах партнёра', overlays or ['Дома недоступны: не указано точное время рождения.']))

    counts = Counter(str(a.get('aspect')) for a in aspects)
    sections.append(('Статистика расчёта', [
        f'Всего межпланетных аспектов: {len(aspects)}',
        'По типам: ' + ', '.join(f'{k} - {counts.get(k, 0)}' for k in ('Соединение','Секстиль','Квадрат','Тригон','Оппозиция')),
        f'Орб до 2°: {sum(1 for a in aspects if float(a.get("orb", 99)) <= 2)}; 2-4°: {sum(1 for a in aspects if 2 < float(a.get("orb", 99)) <= 4)}; более 4°: {sum(1 for a in aspects if float(a.get("orb", 99)) > 4)}',
    ]))
    return sections


def _transit_sort_key(a: dict[str, Any]) -> tuple[float, str, str]:
    return (float(a.get('orb', 99)), str(a.get('transit_planet','')), str(a.get('natal_planet','')))


def _transit_aspect_text(a: dict[str, Any]) -> str:
    tp = str(a.get('transit_planet', ''))
    np = str(a.get('natal_planet', ''))
    aspect = str(a.get('aspect', ''))
    orb = str(a.get('orb_text', ''))
    state = str(a.get('state', ''))
    house = a.get('house')
    retro = ' | ретроградный транзит' if a.get('transit_retrograde') else ''
    sphere = f' | дом {int(house)}: {HOUSE_THEME.get(int(house), "")}' if house else ''
    return f'{tp} {aspect} натальному {np}; орб {orb}; состояние: {state}{retro}{sphere}.'


def _transit_detail(a: dict[str, Any]) -> str:
    tp = str(a.get('transit_planet',''))
    np = str(a.get('natal_planet',''))
    aspect = str(a.get('aspect',''))
    state = str(a.get('state',''))
    house = a.get('house')
    natal_theme = PLANET_ROLE.get(np, 'важная натальная сфера')
    transit_theme = TRANSIT_THEME.get(tp, 'заметная тема периода')
    polarity = _polarity(aspect)
    if polarity == 'hard':
        tone = 'Напряжение здесь может проявиться через'
        if tp == 'Марс': tail = 'поспешные действия, спор, необходимость отстаивать границы или резкий запуск дела'
        elif tp == 'Сатурн': tail = 'задержки, дополнительные обязательства, проверку результата или необходимость принять ограничение'
        elif tp == 'Уран': tail = 'резкую смену плана, отказ от старого формата или неожиданное решение'
        elif tp == 'Плутон': tail = 'сильную внутреннюю перестройку, борьбу за влияние или отказ от прежнего способа управлять ситуацией'
        elif tp == 'Нептун': tail = 'неясность, идеализацию и необходимость перепроверять детали'
        elif tp == 'Меркурий': tail = 'спор из-за слов, документов, сроков или пересмотра решения'
        elif tp == 'Венера': tail = 'чувствительность в отношениях, расходах, симпатиях или вопросах ценности'
        else: tail = 'эмоционально или событийно заметный поворот в этой сфере'
    else:
        tone = 'Поддержка здесь проявляется через'
        if tp == 'Юпитер': tail = 'новый шанс, полезный контакт, расширение возможностей или обучение'
        elif tp == 'Венера': tail = 'сближение, приятную встречу, поддержку, покупку или финансовую возможность'
        elif tp == 'Меркурий': tail = 'удачный разговор, оформление, поездку или быстрое решение'
        elif tp == 'Марс': tail = 'смелое действие, запуск и способность быстро сдвинуть дело'
        elif tp == 'Сатурн': tail = 'структуру, дисциплину и укрепление того, что уже работает'
        else: tail = 'более лёгкое прохождение заметной темы периода'
    state_phrase = {
        'точный': 'На выбранную дату акцент находится в пике.',
        'сходящийся': 'Тема ещё набирает силу.',
        'расходящийся': 'Тема уже выходит из пика и постепенно ослабевает.',
    }.get(state, '')
    sphere = f' Особое внимание - {HOUSE_THEME.get(int(house), "эта сфера")}. ' if house else ' '
    return f'{tone} {tail}. Это затрагивает {natal_theme}, а общий смысл периода связан с темой «{transit_theme}». {state_phrase}{sphere}'


def _timing_line(a: dict[str, Any]) -> str:
    tp, state = str(a.get('transit_planet','')), str(a.get('state',''))
    if tp == 'Луна': horizon = 'часы - 1 день'
    elif tp in {'Солнце','Меркурий','Венера','Марс'}: horizon = 'дни - несколько недель'
    elif tp in {'Юпитер','Сатурн'}: horizon = 'недели - месяцы'
    else: horizon = 'месяцы и дольше'
    if state == 'точный': return f'Пик на выбранную дату; рабочий горизонт: {horizon}.'
    if state == 'сходящийся': return f'Акцент усиливается; ориентир: {horizon}.'
    return f'Акцент уже расходится; развязка: {horizon}.'


