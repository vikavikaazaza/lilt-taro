def _join(items: list[str]) -> str:
    out: list[str] = []
    seen: set[str] = set()
    for item in items:
        text = ' '.join(str(item).split()).strip()
        if not text:
            continue
        if text[-1] not in '.!?':
            text += '.'
        key = text.lower()
        if key not in seen:
            out.append(text)
            seen.add(key)
    return ' '.join(out)


def _angle_points(calc: dict[str, Any]) -> dict[str, list[dict[str, Any]]]:
    out = {'ASC': [], 'DSC': [], 'MC': [], 'IC': []}
    for a in calc.get('angle_aspects', []):
        point = str(a.get('point', ''))
        if point in out:
            out[point].append(a)
    return out


def _overlay_map(calc: dict[str, Any]) -> dict[tuple[int, int], list[str]]:
    out: dict[tuple[int, int], list[str]] = {}
    for x in calc.get('overlays_1_in_2', []):
        h = int(x.get('house', 0) or 0)
        if h:
            out.setdefault((2, h), []).append(str(x.get('planet', '')))
    for x in calc.get('overlays_2_in_1', []):
        h = int(x.get('house', 0) or 0)
        if h:
            out.setdefault((1, h), []).append(str(x.get('planet', '')))
    return out


