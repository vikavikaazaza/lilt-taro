def _transit_timing(a: dict[str, Any]) -> str:
    tp = str(a.get('transit_planet', ''))
    state = str(a.get('state', ''))
    if tp == 'Луна':
        period = 'несколько часов — 1 день'
    elif tp in {'Солнце', 'Меркурий', 'Венера', 'Марс'}:
        period = 'несколько дней — 2–3 недели'
    elif tp in {'Юпитер', 'Сатурн'}:
        period = 'несколько недель — несколько месяцев'
    else:
        period = 'несколько месяцев и дольше'

    if state == 'точный':
        return f'Пик приходится на выбранную дату; проявление легче заметить именно сейчас. Рабочий горизонт: {period}.'
    if state == 'сходящийся':
        return f'Влияние усиливается. Если событие ещё не произошло, повод может проявиться в ближайшем периоде: {period}.'
    return f'Пик уже проходит. Сейчас вероятнее последствия, завершение разговора или оформление того, что началось раньше. Горизонт: {period}.'


