def _name_case(name: str, case: str) -> str:
    """Нужные формы имени для естественных фраз в отчёте.

    case:
      nom — именительный
      gen — родительный
      ins — творительный
      dat — дательный
    """
    raw = ' '.join(str(name or '').split()).strip()
    if not raw or case not in {'nom', 'gen', 'ins', 'dat'}:
        return raw

    first, *rest = raw.split()
    forms = _NAME_CASES.get(first.lower())
    if forms:
        # Старый словарь хранит gen/ins; dat добавляем отдельно для имён,
        # которые реально используются в текстах. Если формы нет —
        # оставляем имя как есть, а не придумываем неправильное окончание.
        if case == 'gen':
            first_form = forms[0]
        elif case == 'ins':
            first_form = forms[1]
        elif case == 'dat':
            dat_forms = {
                'виктория': 'Виктории', 'мария': 'Марии', 'анна': 'Анне',
                'елена': 'Елене', 'ольга': 'Ольге', 'ирина': 'Ирине',
                'екатерина': 'Екатерине', 'ксения': 'Ксении', 'наталья': 'Наталье',
                'татьяна': 'Татьяне', 'анастасия': 'Анастасии', 'алина': 'Алине',
                'карина': 'Карине', 'кристина': 'Кристине', 'диана': 'Диане',
                'лилия': 'Лилии', 'светлана': 'Светлане',
                'даниил': 'Даниилу', 'алексей': 'Алексею', 'андрей': 'Андрею',
                'сергей': 'Сергею', 'дмитрий': 'Дмитрию', 'михаил': 'Михаилу',
                'александр': 'Александру', 'евгений': 'Евгению', 'максим': 'Максиму',
                'роман': 'Роману', 'артём': 'Артёму', 'артем': 'Артему',
                'никита': 'Никите', 'николай': 'Николаю', 'константин': 'Константину',
                'владимир': 'Владимиру', 'владислав': 'Владиславу', 'виктор': 'Виктору',
                'павел': 'Павлу', 'илья': 'Илье', 'иван': 'Ивану', 'кирилл': 'Кириллу',
                'денис': 'Денису', 'тимофей': 'Тимофею', 'фёдор': 'Фёдору',
                'федор': 'Федору', 'георгий': 'Георгию', 'глеб': 'Глебу',
                'олег': 'Олегу', 'антон': 'Антону', 'арсений': 'Арсению',
                'матвей': 'Матвею', 'степан': 'Степану', 'игорь': 'Игорю',
                'борис': 'Борису',
            }
            first_form = dat_forms.get(first.lower(), first)
        else:
            first_form = first
        return ' '.join([first_form, *rest])

    # Простые правила для новых имён, чтобы не ломать текст при добавлении
    # пользователя с именем, которого нет в словаре.
    low = first.lower()
    if case == 'nom':
        return raw
    fallback = {
        'gen': {
            'а': 'ы', 'я': 'и', 'ь': 'я', 'й': 'я', 'а́': 'ы',
        },
        'ins': {
            'а': 'ой', 'я': 'ей', 'ь': 'ем', 'й': 'ем',
        },
        'dat': {
            'а': 'е', 'я': 'е', 'ь': 'ю', 'й': 'ю',
        },
    }
    endings = fallback.get(case, {})
    for ending, replacement in endings.items():
        if low.endswith(ending) and len(first) > len(ending) + 1:
            stem = first[:-len(ending)] if ending else first
            return ' '.join([stem + replacement, *rest])
    return raw

